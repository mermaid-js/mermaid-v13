/**
 * Ports v12's gitGraph specs (R-TEST-3) into `src/v12-specs/`, run against v13's parser and
 * model through `src/v12-specs/adapter.ts`: v12's `parser` and gitGraph DB getters (and the
 * `log` the duplicate-id test spies on) for the diagram spec, and the Langium `gitGraphParse`
 * result for the parser package's spec. The spec bodies are copied unchanged from the last v12
 * commit; only imports are rewritten, and tests listed in `SKIP` (with a reason) are turned
 * into `it.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-gitgraph port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const V12 = 'fa796a943';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));

interface Source {
  /** Path at {@link V12}. */
  file: string;
  /** File name in `src/v12-specs/`. */
  name: string;
  /** The imports that replace the spec's own. */
  imports: string[];
}

const SOURCES: Source[] = [
  {
    file: 'packages/mermaid/src/diagrams/git/gitGraph.spec.ts',
    name: 'gitGraph.spec.ts',
    imports: [
      "import { beforeEach, describe, expect, it, vi } from 'vitest';",
      "import { db, log, parser } from './adapter.ts';",
    ],
  },
  {
    file: 'packages/parser/tests/gitGraph.test.ts',
    name: 'langium-gitGraph.spec.ts',
    imports: [
      "import { describe, expect, it } from 'vitest';",
      "import { gitGraphParse as parse } from './adapter.ts';",
    ],
  },
];

/** mermaid\@12 rejects the text; only Langium's error recovery built the statements asserted. */
const RECOVERED =
  "mermaid@12 rejects this text (a Langium parse error, checked through the oracle in packages/conformance); the assertions read the statements Langium's error recovery built, and v13 builds none for a statement with a syntax error";

/** `file name: { test title (or its unique start): reason }`. Reasons are written into the file. */
export const SKIP: Record<string, Record<string, string>> = {
  'gitGraph.spec.ts': {
    'should expose getConfig method':
      "v13's parse holds no config: the gitGraph config section is read by the plugin (#374)",
    'should return config with showBranches property': 'as above (#374)',
    'should return config with showCommitLabel property': 'as above (#374)',
    'should return config with rotateCommitLabel property': 'as above (#374)',
    'should return config with parallelCommits property': 'as above (#374)',
  },
  'langium-gitGraph.spec.ts': {
    'should ignore malformed properties and not break parsing': RECOVERED,
    'should ignore malformed properties in merge statements': RECOVERED,
    'should parse cherry-picking with a commit id': RECOVERED,
  },
};

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

let total = 0;
let skipped = 0;
for (const { file, name, imports } of SOURCES) {
  let body = git('show', `${V12}:${file}`)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line))
    .join('\n');
  const notes: string[] = [];
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    ...imports,
    ...notes,
    '',
  ].join('\n');
  writeFileSync(join(OUT, name), header + body);
}
process.stdout.write(`${SOURCES.length} files, ${total} tests (${skipped} skipped)\n`);
