/**
 * Ports v12's architecture specs (R-TEST-3) into `src/v12-specs/`, run against v13's parser
 * through `src/v12-specs/adapter.ts`: v12's `parser` and `ArchitectureDB` for the diagram spec,
 * `@mermaid-js/parser`'s Langium parse for the parser package's spec, and the seed spec, skipped
 * whole (D328). The spec bodies are copied unchanged from the last v12 commit; only imports are
 * rewritten, and tests listed in `SKIP` (with a reason) are turned into `it.skip` /
 * `describe.skip`. `svgDraw.spec.ts` (v12's element ids) is carried over by hand in `src/render/render.spec.ts` (#614), as `data-id`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-architecture port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const V12 = 'fa796a943';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));

interface Source {
  /** Path at {@link V12}. */
  file: string;
  /** File name in `src/v12-specs/`. */
  name: string;
  /** The imports that replace the spec's own. */
  imports: string[];
}

const SOURCES: Source[] = [
  {
    file: 'packages/mermaid/src/diagrams/architecture/architecture.spec.ts',
    name: 'architecture.spec.ts',
    imports: [
      "import { afterEach, assert, beforeEach, describe, expect, it, vi } from 'vitest';",
      "import { ArchitectureDB, parser, resetConfig, setConfig } from './adapter.ts';",
    ],
  },
  {
    file: 'packages/parser/tests/architecture.test.ts',
    name: 'langium-architecture.spec.ts',
    imports: [
      "import { describe, expect, it } from 'vitest';",
      "import { Architecture, architectureParse as parse, expectNoErrorsOrAlternatives } from './adapter.ts';",
    ],
  },
  {
    file: 'packages/mermaid/src/diagrams/architecture/architectureSeed.spec.ts',
    name: 'architectureSeed.spec.ts',
    imports: ["import { describe, expect, it } from 'vitest';"],
  },
];

/** fcose's knobs and data structures, which v13 does not have (D328). */
const FCOSE =
  "v12's fcose layout (cytoscape, its seeded `Math.random`, its config knobs and BFS data structures) is not ported: `compass` places the diagram, deterministic by construction (D326, D328)";

/** `file name: { test title (or its unique start): reason }`. Reasons are written into the file. */
export const SKIP: Record<string, Record<string, string>> = {
  'architecture.spec.ts': {
    'cytoscape stylesheet warnings': FCOSE,
    'randomize config': `${FCOSE}; the parse counts of its second test are in \`parse.spec.ts\` and the corpus`,
    'fcose layout config': FCOSE,
    'should block proto pollution via service id': `${FCOSE}; \`__proto__\` ids are in \`parse.spec.ts\``,
  },
  'architectureSeed.spec.ts': {
    withSeededRandom: FCOSE,
  },
};

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

let total = 0;
let skipped = 0;
for (const { file, name, imports } of SOURCES) {
  let body = git('show', `${V12}:${file}`)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line))
    .join('\n');
  const notes: string[] = [];
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip|\.each\([^)]*\))?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    ...imports,
    ...notes,
    '',
  ].join('\n');
  writeFileSync(join(OUT, name), header + body);
}
process.stdout.write(`${SOURCES.length} files, ${total} tests (${skipped} skipped)\n`);
