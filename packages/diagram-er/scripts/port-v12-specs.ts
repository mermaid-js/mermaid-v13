/**
 * Ports v12's ER parser specs (R-TEST-3) into `src/v12-specs/`, run against v13's parser
 * through `src/v12-specs/adapter.ts`, which exposes the parse result with v12's ErDB method
 * names. The spec bodies are copied unchanged from the last v12 commit; only imports are
 * rewritten, and tests listed in `SKIP` (with a reason) are turned into `it.skip`.
 *
 * Not ported: `erDb.spec.js` calls v12's DB methods (`addSubGraph`, …) with no parse; v13 has
 * no DB, and the parse-level subgraph behaviour is covered by `subgraph.spec.js` and the
 * conformance parity suite. `erRenderer.spec.ts` tests the v12 renderer.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-er port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const V12 = 'fa796a943';
const DIR = 'packages/mermaid/src/diagrams/er/parser';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));

/** `file: { test title (or its unique start): reason }`. Reasons are written into the file. */
export const SKIP: Record<string, Record<string, string>> = {};

/**
 * v12 specs that match jison's message text keep only the rejection: v13 messages never name
 * tokens (R-ERR-5).
 */
const JISON_MESSAGE = /\.toThrow(Error)?\((["'`])[^"'`]*(?:got '|Expecting ')[^)]*\)/g;

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

const files = git('ls-tree', '--name-only', V12, `${DIR}/`)
  .split('\n')
  .filter((f) => f.endsWith('.spec.js'))
  .sort();
let total = 0;
let skipped = 0;
for (const file of files) {
  const name = file.slice(DIR.length + 1).replace(/\.js$/, '.ts');
  let body = git('show', `${V12}:${file}`)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line))
    .join('\n');
  const notes: string[] = [];
  body = body.replace(JISON_MESSAGE, (_m, error = '') => {
    notes.push('// rewritten: a jison message check keeps only the rejection (R-ERR-5)');
    return `.toThrow${error}()`;
  });
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    "import { beforeEach, describe, expect, it } from 'vitest';",
    "import erDiagram, { ErDB, setConfig } from './adapter.ts';",
    ...new Set(notes),
    '',
  ].join('\n');
  writeFileSync(join(OUT, name), header + body);
}
process.stdout.write(`${files.length} files, ${total} tests (${skipped} skipped)\n`);
