/**
 * Reading the config JSON schema from gen-config (D60, D96): `$ref`/`allOf` resolution and
 * the key rules `resolveConfig` uses (core's generated key tree is built by the same rules).
 */

/** A JSON Schema node as gen-config writes it. Loose on purpose. */
export interface SchemaNode {
  readonly $ref?: string;
  readonly allOf?: readonly SchemaNode[];
  readonly type?: string | readonly string[];
  readonly properties?: Readonly<Record<string, SchemaNode>>;
  readonly additionalProperties?: boolean | SchemaNode;
  readonly default?: unknown;
  readonly description?: string;
  readonly enum?: readonly unknown[];
  readonly 'meta:enum'?: Readonly<Record<string, string>>;
  readonly 'x-mermaid'?: Annotation;
  readonly [keyword: string]: unknown;
}

/** The `x-mermaid` compatibility annotation of a key (D60). */
export interface Annotation {
  readonly status: 'honoured' | 'ignored' | 'pending' | 'removed' | 'moved';
  readonly since?: string;
  readonly movedTo?: string;
  readonly replacement?: string;
  readonly reason?: string;
}

/** The whole config schema (`configSchema`, generated by `pnpm gen:config`). */
export interface ConfigSchema extends SchemaNode {
  readonly $defs?: Readonly<Record<string, SchemaNode>>;
}

/**
 * How a key's value is checked: `closed` = an object with known keys (an unknown one warns),
 * `open` = an object with free keys (`themeVariables`), `leaf` = anything else.
 */
export type KeyShape = 'closed' | 'open' | 'leaf';

const WHOLE_DEF = /^#\/\$defs\/([^/]+)$/;

export class SchemaView {
  constructor(readonly root: ConfigSchema) {}

  /** The node a local `#/…` pointer names. */
  private pointer(ref: string): SchemaNode | undefined {
    if (!ref.startsWith('#/')) return undefined;
    let node: unknown = this.root;
    for (const part of ref.slice(2).split('/')) {
      node =
        typeof node === 'object' && node !== null
          ? (node as Record<string, unknown>)[part]
          : undefined;
    }
    return typeof node === 'object' && node !== null ? (node as SchemaNode) : undefined;
  }

  /**
   * A key's node with a `$ref` to another def's property merged in (the key's own fields win),
   * as gen-config documents it. A `$ref` to a whole def stays as it is.
   */
  resolve(node: SchemaNode): SchemaNode {
    const ref = node.$ref;
    if (ref === undefined || WHOLE_DEF.test(ref)) return node;
    const target = this.pointer(ref);
    return target === undefined ? node : { ...this.resolve(target), ...node, $ref: undefined };
  }

  /** Every property of an object node, following `$ref` and `allOf`, in declaration order. */
  properties(node: SchemaNode, depth = 0): Map<string, SchemaNode> {
    const out = new Map<string, SchemaNode>();
    if (depth > 16) return out;
    const target = node.$ref === undefined ? undefined : this.pointer(node.$ref);
    if (target !== undefined) {
      for (const [k, v] of this.properties(target, depth + 1)) out.set(k, v);
    }
    for (const part of node.allOf ?? []) {
      for (const [k, v] of this.properties(part, depth + 1)) out.set(k, v);
    }
    for (const [k, v] of Object.entries(node.properties ?? {})) out.set(k, v);
    return out;
  }

  /** The rules of core's key tree (`resolveConfig`), so the service warns where a render does. */
  shape(node: SchemaNode): KeyShape {
    const whole = node.$ref === undefined ? undefined : WHOLE_DEF.exec(node.$ref)?.[1];
    if (whole !== undefined) {
      const def = this.root.$defs?.[whole];
      return def !== undefined && this.properties(def).size > 0 ? 'closed' : leafShape(def);
    }
    const n = this.resolve(node);
    if (n.additionalProperties !== undefined && n.additionalProperties !== false) return 'open';
    if (n.properties !== undefined || n.allOf !== undefined) return 'closed';
    return leafShape(n);
  }

  /** The root keys that are a diagram's config section (`flowchart`): a `$ref` to a whole def. */
  isDiagramSection(key: string): boolean {
    const ref = this.root.properties?.[key]?.$ref;
    return ref !== undefined && WHOLE_DEF.test(ref);
  }

  /** The node at a config path (`['flowchart', 'curve']`), when the schema declares it. */
  at(path: readonly string[]): SchemaNode | undefined {
    let node: SchemaNode | undefined = this.root;
    for (const key of path) {
      node = node === undefined ? undefined : this.properties(node).get(key);
    }
    return node;
  }
}

function leafShape(node: SchemaNode | undefined): KeyShape {
  const types = node?.type === undefined ? [] : [node.type].flat();
  return types.length > 0 && !types.includes('object') ? 'leaf' : 'open';
}

/** The compatibility status of a key; keys without an annotation count as honoured. */
export function annotationOf(node: SchemaNode): Annotation {
  return node['x-mermaid'] ?? { status: 'honoured' };
}

/** A key's type as the config reference prints it: its enum, else its JSON type. */
export function typeText(node: SchemaNode): string {
  if (node.enum !== undefined) return node.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (node.$ref !== undefined && WHOLE_DEF.test(node.$ref)) return 'object';
  return node.type === undefined ? 'any' : [node.type].flat().join(' | ');
}
