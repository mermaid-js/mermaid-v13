/**
 * Ports v12's treeView specs (R-TEST-3) into `src/v12-specs/`, run against v13's parser through
 * `src/v12-specs/adapter.ts`: the diagram's `parser.spec.ts`, `boxDrawingPreprocessor.spec.ts`,
 * `db.spec.ts` and `icons.spec.ts`, and the parser package's `treeView.test.ts` and
 * `treeViewValueConverter.test.ts`. The spec bodies are copied unchanged from the last v12
 * commit; only imports are rewritten, and tests listed in `SKIP` (with a reason) are turned into
 * `it.skip` / `describe.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-treeview port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const V12 = 'fa796a943';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));
const DIAGRAM = 'packages/mermaid/src/diagrams/treeView';

interface Source {
  /** Path at {@link V12}. */
  file: string;
  /** File name in `src/v12-specs/`. */
  name: string;
  /** The imports that replace the spec's own. */
  imports: string[];
}

const vitest = (...names: string[]) => `import { ${names.join(', ')} } from 'vitest';`;

const SOURCES: Source[] = [
  {
    file: `${DIAGRAM}/parser.spec.ts`,
    name: 'parser.spec.ts',
    imports: [
      vitest('beforeEach', 'describe', 'expect', 'it'),
      "import { db, parser } from './adapter.ts';",
    ],
  },
  {
    file: `${DIAGRAM}/boxDrawingPreprocessor.spec.ts`,
    name: 'boxDrawingPreprocessor.spec.ts',
    imports: [
      vitest('describe', 'expect', 'it'),
      "import { isBoxDrawingFormat, preprocessBoxDrawing, remapErrorLines } from './adapter.ts';",
    ],
  },
  {
    file: `${DIAGRAM}/db.spec.ts`,
    name: 'db.spec.ts',
    imports: [
      vitest('beforeEach', 'describe', 'expect', 'it'),
      "import { db } from './adapter.ts';",
    ],
  },
  {
    file: `${DIAGRAM}/icons.spec.ts`,
    name: 'icons.spec.ts',
    imports: [
      vitest('describe', 'expect', 'it'),
      "import { detectIcon, getNodeIcon, treeViewIcons } from './adapter.ts';",
    ],
  },
  {
    file: 'packages/parser/tests/treeView.test.ts',
    name: 'langium-treeView.spec.ts',
    imports: [
      vitest('describe', 'expect', 'it'),
      "import { createTreeViewServices, expectNoErrorsOrAlternatives } from './adapter.ts';",
    ],
  },
  {
    file: 'packages/parser/tests/treeViewValueConverter.test.ts',
    name: 'langium-value-converter.spec.ts',
    imports: [
      vitest('describe', 'expect', 'it'),
      "import { TreeViewValueConverter } from './adapter.ts';",
    ],
  },
];

const NO_REMAP =
  'v13 rewrites no message: its diagnostics carry source ranges, at the source line and column (D486); the line map is checked against v12 by the conformance box-mode gate';

/** `file name: { test title (or its unique start): reason }`. Reasons are written into the file. */
export const SKIP: Record<string, Record<string, string>> = {
  'boxDrawingPreprocessor.spec.ts': { remapErrorLines: NO_REMAP },
  'db.spec.ts': {
    getConfig:
      'the treeView options (`getConfig`) are ported with the config work in T5 (#577), see GAPS T5',
  },
  'icons.spec.ts': {
    'treeViewIcons pack':
      'D485: treeView registers no icon pack; it draws its file and folder glyphs itself (T4 #575)',
  },
};

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

let total = 0;
let skipped = 0;
for (const { file, name, imports } of SOURCES) {
  let body = git('show', `${V12}:${file}`);
  // Drop the spec's imports, single- or multi-line.
  body = body.replace(/^import [^;]*?from ['"][^'"]+['"];\n/gms, '');
  const notes: string[] = [];
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    ...imports,
    ...notes,
    '',
  ].join('\n');
  skipped += countSkipped(body);
  writeFileSync(join(OUT, name), header + body);
}
process.stdout.write(`${SOURCES.length} files, ${total} tests (${skipped} skipped)\n`);

/** Tests under `it.skip`, or inside a `describe.skip` block. */
function countSkipped(body: string): number {
  let n = 0;
  const lines = body.split('\n');
  let depth = -1;
  for (const line of lines) {
    const indent = line.length - line.trimStart().length;
    if (depth >= 0 && line.trim() !== '' && indent <= depth && /^\s*\}\);/.test(line)) {
      depth = -1;
      continue;
    }
    if (depth < 0 && /\bdescribe\.skip\(/.test(line)) depth = indent;
    else if (/\bit\.skip\(/.test(line) || (depth >= 0 && /\bit\(/.test(line))) n++;
  }
  return n;
}
