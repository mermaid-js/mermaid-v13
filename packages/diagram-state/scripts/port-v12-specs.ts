/**
 * Ports v12's state parser and DB specs (R-TEST-3) into `src/v12-specs/`, run against v13's
 * parser through `src/v12-specs/adapter.ts`, which exposes the parse result with v12's StateDB
 * method names. The spec bodies are copied unchanged from the last v12 commit; only imports
 * are rewritten, and tests listed in `SKIP` (with a reason) are turned into `it.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-state port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const V12 = 'fa796a943';
const DIR = 'packages/mermaid/src/diagrams/state';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));

const LAYOUT =
  "asserts v12's render data (`getData`: note groups, edge dash patterns, palette slots), which the state layout builder (#144) and renderer (#146) produce";
const PURIFY =
  "expects DOMPurify's serialisation (`<br/>` read back as `<br>`); v13 keeps the text as written and sanitises when it writes SVG, and the oracle (sanitising off) agrees";
const DB =
  "calls v12's StateDB methods directly, with no source to parse; the same behaviour is checked through the parse by the oracle parity suite";

/** `file: { test or describe title (or its unique start): reason }`. Reasons are written into the file. */
export const SKIP: Record<string, Record<string, string>> = {
  'stateNoteEdge.spec.ts': { 'state note edges': LAYOUT },
  'stateNoteNode.spec.ts': { 'state diagram note nodes': LAYOUT },
  'stateDiagram-colorIndex.spec.ts': { 'state diagram colour slots': LAYOUT },
  'stateDb.spec.ts': { 'State Diagram stateDb': DB, 'state db class': DB },
  'stateDiagram-v2.spec.ts': {
    'should handle note statements': PURIFY,
    'should handle multiline notes with different line breaks': PURIFY,
  },
  'stateDiagram.spec.ts': {
    'should store links from click statements manually passed to extract()': DB,
  },
};

/**
 * v12 specs that match jison's message text (`got 'PS'`, `Expecting 'SQE'`) keep only the
 * rejection: v13 messages never name tokens (R-ERR-5).
 */
const JISON_MESSAGE = /\.toThrow(Error)?\((["'`])[^"'`]*(?:got '|Expecting ')[^)]*\)/g;

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

const files = git('ls-tree', '-r', '--name-only', V12, `${DIR}/`)
  .split('\n')
  .filter((f) => /\.spec\.[jt]s$/.test(f) && !f.includes('Renderer'))
  .sort();
let total = 0;
let skipped = 0;
for (const file of files) {
  const name = (file.split('/').pop() ?? file).replace(/\.js$/, '.ts');
  let body = git('show', `${V12}:${file}`)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line))
    .join('\n');
  const notes: string[] = [];
  body = body.replace(JISON_MESSAGE, (_m, error = '') => {
    notes.push('// rewritten: a jison message check keeps only the rejection (R-ERR-5)');
    return `.toThrow${error}()`;
  });
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe|it\.each\([^)]*\))\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        const plain = t.replace(/\\(.)/g, '$1');
        if (
          !plain.startsWith(title) &&
          !(fn.startsWith('it.each') && title.startsWith(plain.split('%s')[0] ?? '\0'))
        )
          return m;
        hit++;
        return `${fn.replace(/^(it|describe)/, '$1.skip')}(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    "import { afterEach, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';",
    "import stateDiagram, { DEFAULT_DIAGRAM_DIRECTION, parser, setConfig, StateDB } from './adapter.ts';",
    ...new Set(notes),
    '',
  ].join('\n');
  writeFileSync(join(OUT, name), header + body);
}
process.stdout.write(`${files.length} files, ${total} tests (${skipped} skipped)\n`);
