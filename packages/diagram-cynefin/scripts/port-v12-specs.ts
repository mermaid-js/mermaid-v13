/**
 * Ports v12's cynefin specs (R-TEST-3) into `src/v12-specs/`, run against v13's parser through
 * `src/v12-specs/adapter.ts`: v12's `parser` and cynefin DB (#465). The spec bodies are copied
 * unchanged from the last v12 commit; only imports are rewritten (the boundary cases run through
 * the render seam, T4 #468: the paths the renderer writes), and tests listed in `SKIP`
 * (with a reason) are turned into `it.skip` / `describe.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-cynefin port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The in-repo v12 commit; its cynefin sources are `mermaid@12.2.0`'s byte for byte (#461). */
const V12 = 'fa796a943';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));

interface Source {
  /** Path at {@link V12}. */
  file: string;
  /** File name in `src/v12-specs/`. */
  name: string;
  /** The imports that replace the spec's own. */
  imports: string[];
}

const DIR = 'packages/mermaid/src/diagrams/cynefin';

const SOURCES: Source[] = [
  {
    file: `${DIR}/cynefin.spec.ts`,
    name: 'cynefin.spec.ts',
    imports: [
      "import { beforeEach, describe, expect, it } from 'vitest';",
      'import {',
      '  db,',
      '  generateCliffPath,',
      '  generateConfusionPath,',
      '  generateFoldPath,',
      '  generateHorizontalBoundary,',
      '  hashString,',
      '  resolveSeed,',
      '  seededRandom,',
      "} from './adapter.ts';",
    ],
  },
  {
    file: `${DIR}/cynefin.integration.spec.ts`,
    name: 'cynefin.integration.spec.ts',
    imports: [
      "import { beforeEach, describe, expect, it } from 'vitest';",
      "import { db, parser } from './adapter.ts';",
    ],
  },
];

/** `file name: { test title (or its unique start): reason }`. Reasons are written into the file. */
export const SKIP: Record<string, Record<string, string>> = {};

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

let total = 0;
let skipped = 0;
for (const { file, name, imports } of SOURCES) {
  let body = git('show', `${V12}:${file}`)
    .replace(/^import (?:type )?\{[^}]*\} from ['"][^'"]+['"];\n/gm, '')
    .replace(/^import .* from ['"].*\n/gm, '');
  const notes: string[] = [];
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\bit\.skip\(/g) ?? []).length;
  for (const m of body.matchAll(
    /\bdescribe\.skip\((['"`])(?:(?!\1)[^\\]|\\.)*\1[\s\S]*?\n\}\);/g
  )) {
    skipped += (m[0].match(/\bit\(/g) ?? []).length;
  }
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    ...imports,
    ...notes,
    '',
  ].join('\n');
  writeFileSync(join(OUT, name), header + body);
}
process.stdout.write(`${SOURCES.length} files, ${total} tests (${skipped} skipped)\n`);
