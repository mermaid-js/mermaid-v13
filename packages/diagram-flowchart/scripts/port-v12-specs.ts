/**
 * Ports v12's flowchart parser specs (R-TEST-3) into `src/v12-specs/`, run against v13's
 * parser through `src/v12-specs/adapter.ts`, which exposes the parse result with v12's FlowDB
 * method names. The spec bodies are copied unchanged from the last v12 commit; only imports
 * are rewritten, and tests listed in `SKIP` (with a reason) are turned into `it.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-flowchart port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const V12 = 'fa796a943';
const DIR = 'packages/mermaid/src/diagrams/flowchart/parser';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));

/** `file: { test title: reason }`. Reasons are reported in the generated file. */
const LATER =
  'v12 behaviour added after mermaid@12.2.0, the oracle, which rejects this input; it arrives with the oracle bump (R-COMPAT-8)';
const LAYOUT = "asserts v12's LayoutData (getData), which the renderer builds (#14)";

/** `file: { test or describe title (or its unique start): reason }`. Reasons are written into the file. */
export const SKIP: Record<string, Record<string, string>> = {
  'flow-edges.spec.ts': {
    'edge ids attached to the preceding node (#7032)': LATER,
  },
  'flow-node-data.spec.ts': {
    'should order edges for the step animation': LAYOUT,
    'should give step edges the default step duration': LAYOUT,
    'should take the step duration from the flowchart config': LAYOUT,
    'should mark step edges for a number badge only when stepNumbers is on': LAYOUT,
  },
  'subgraph.spec.ts': {
    'should attach `@{ view: collapsed }` metadata to a subgraph and collapse it': LAYOUT,
  },
  'flow.spec.ts': {
    "should be able to parse a '<'":
      "expects DOMPurify's `&lt;`; v13 keeps label text as written and escapes it when writing SVG",
  },
  'flow-style.spec.ts': {
    'should keep node label text (if already defined) when a style is applied':
      "the spec feeds jison directly; through v12's pipeline (the oracle) `#fff;` becomes an entity and the text is rejected, as v13 does",
  },
};

/**
 * v12 specs that match jison's message text (`got 'PS'`, `Expecting 'SQE'`) keep only the
 * rejection: v13 messages never name tokens (R-ERR-5).
 */
const JISON_MESSAGE = /\.toThrow(Error)?\((["'`])[^"'`]*(?:got '|Expecting ')[^)]*\)/g;

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

const files = git('ls-tree', '--name-only', V12, `${DIR}/`)
  .split('\n')
  .filter((f) => f.endsWith('.spec.js'))
  .sort();
let total = 0;
let skipped = 0;
for (const file of files) {
  const name = file.slice(DIR.length + 1).replace(/\.js$/, '.ts');
  let body = git('show', `${V12}:${file}`)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line))
    .join('\n');
  const notes: string[] = [];
  body = body.replace(JISON_MESSAGE, (_m, error: string | undefined) => {
    notes.push('// rewritten: a jison message check keeps only the rejection (R-ERR-5)');
    return `.toThrow${error ?? ''}()`;
  });
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe|it\.each\([^)]*\))\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        const plain = t.replace(/\\(.)/g, '$1');
        if (
          !plain.startsWith(title) &&
          !(fn.startsWith('it.each') && title.startsWith(plain.split('%s')[0] ?? '\0'))
        )
          return m;
        hit++;
        return `${fn.replace(/^(it|describe)/, '$1.skip')}(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    "import { afterEach, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';",
    "import flow, { cleanupComments, FlowDB, getConfig, log, setConfig } from './adapter.ts';",
    ...new Set(notes),
    '',
  ].join('\n');
  writeFileSync(join(OUT, name), header + body);
}
process.stdout.write(`${files.length} files, ${total} tests (${skipped} skipped)\n`);
