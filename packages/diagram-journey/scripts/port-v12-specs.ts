/**
 * Ports v12's journey parser spec (R-TEST-3) into `src/v12-specs/`, run against v13's parser
 * through `src/v12-specs/adapter.ts`: `parser.parse` parses with v13 and loads the model into
 * `journeyDb`, which answers as v12's DB did. The spec body is copied unchanged from the last
 * v12 commit; only imports are rewritten, and tests listed in `SKIP` (with a reason) are turned
 * into `it.skip`. v12's `journeyDb.spec.js` drives the DB directly (no source text), so its
 * cases are parse-level model specs in `src/parser/parse.spec.ts` instead.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-journey port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const V12 = 'fa796a943';
const DIR = 'packages/mermaid/src/diagrams/user-journey';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));
/** v12 file → ported file name (`.ts`, so the workspace's spec glob runs it). */
const FILES: Record<string, string> = { 'parser/journey.spec.js': 'journey.spec.ts' };

/** `file: { test title (or its unique start): reason }`. Reasons are written into the file. */
const SKIP: Record<string, Record<string, string>> = {};

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

let total = 0;
let skipped = 0;
for (const [file, name] of Object.entries(FILES)) {
  let body = git('show', `${V12}:${DIR}/${file}`)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line))
    .join('\n');
  const notes: string[] = [];
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${DIR}/${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    "import { beforeEach, describe, expect, it } from 'vitest';",
    "import { journeyDb, parser } from './adapter.ts';",
    ...notes,
    '',
  ].join('\n');
  writeFileSync(join(OUT, name), header + body);
}
process.stdout.write(`${Object.keys(FILES).length} files, ${total} tests (${skipped} skipped)\n`);
