/**
 * Ports v12's sequence parser specs (R-TEST-3) into `src/v12-specs/`, run against v13's parser
 * through `src/v12-specs/adapter.ts`, which exposes the parse result with v12's
 * `Diagram.fromText`, `mermaidAPI.parse` and `SequenceDB` names. The spec bodies are copied
 * unchanged from the last v12 commit; only imports are rewritten, the `d3` mock (for v12's
 * renderer) is dropped, and tests listed in `SKIP` (with a reason) become `it.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-sequence port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const V12 = 'fa796a943';
const DIR = 'packages/mermaid/src/diagrams/sequence';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));

/** The specs that parse; the others test v12's renderer and svgDraw with a mocked DOM. */
const FILES = ['sequenceDiagram.spec.js', 'keywordActors.spec.ts'];

const RENDER =
  "asserts v12's internal `bounds` object, which only v12's renderer fills; v13's layout has its own invariants (`sequenceLayoutViolations`)";

/** `file: { test or describe title (or its unique start): reason }`. Reasons are written into the file. */
export const SKIP: Record<string, Record<string, string>> = {
  'sequenceDiagram.spec.ts': {
    'when checking the bounds in a sequenceDiagram': RENDER,
    'when rendering a sequenceDiagram APA': RENDER,
    'when rendering a sequenceDiagram with actor mirror activated': RENDER,
    'should have functions used in sequence JISON as own property':
      "checks the methods v12's jison grammar called on its DB; v13 has no jison DB",
  },
  'keywordActors.spec.ts': {
    'parses a details statement':
      'reads the menu from a DOM element; v13 keeps the element id on the AST for plugin-interactions (D105)',
  },
};

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

/** Drop a top-level `vi.mock('d3', …);` call. */
function dropD3Mock(body: string): string {
  const start = body.indexOf("vi.mock('d3'");
  if (start < 0) return body;
  const end = body.indexOf('\n});\n', start);
  return body.slice(0, start) + body.slice(end + 5);
}

let total = 0;
let skipped = 0;
for (const file of FILES) {
  const name = file.replace(/\.js$/, '.ts');
  let body = git('show', `${V12}:${DIR}/${file}`)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line) && !line.startsWith('// @ts-ignore'))
    .filter((line) => line.trim() !== 'addDiagrams();')
    .join('\n');
  body = dropD3Mock(body).replace(/\bjsdomIt\(/g, 'it(');
  const notes: string[] = [];
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${DIR}/${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    "import { afterEach, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';",
    "import { Diagram, mermaidAPI, parser, SequenceDB, setSiteConfig } from './adapter.ts';",
    ...notes,
    '',
  ].join('\n');
  writeFileSync(join(OUT, name), header + body);
}
process.stdout.write(`${FILES.length} files, ${total} tests (${skipped} skipped)\n`);
