// cspell:words drawables
/**
 * Ports v12's XY chart parser, DB and chart-builder specs (R-TEST-3) into `src/v12-specs/`. The
 * parser and DB specs run against v13's parser through `src/v12-specs/adapter.ts`:
 * `parser.parse` parses with v13 and replays the statements onto `parser.yy` as v12's grammar
 * called its DB, and `db` is v12's DB API over v13's model builder. The chart title and legend
 * specs run against v13's layout and renderer through `src/v12-specs/chart-adapter.ts`, which
 * reads v12's drawables back from the SVG. The spec bodies are copied unchanged from the last
 * v12 commit; only imports
 * are rewritten, v12's own error texts are dropped from `toThrowError` (v13 messages name
 * constructs in Mermaid terms, R-ERR-5), the expectations listed in `REWRITE` (with a reason)
 * are replaced, and tests listed in `SKIP` (with a reason) are turned into `it.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-xychart port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const V12 = 'fa796a943';
const DIR = 'packages/mermaid/src/diagrams/xychart';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));
/** Each spec and the adapter import that replaces its v12 imports. */
const PARSER = "import { db, parser } from './adapter.ts';";
const CHART = "import { defaultConfig, themes, XYChartBuilder } from './chart-adapter.ts';";
const LEGEND =
  "import { ChartLegend, defaultConfig, getChartLegendComponent, themes, XYChartBuilder } from './chart-adapter.ts';";
const FILES: readonly (readonly [file: string, imports: string])[] = [
  ['parser/xychart.jison.spec.ts', PARSER],
  ['xychartDb.spec.ts', PARSER],
  ['chartBuilder/components/chartTitle.spec.ts', CHART],
  ['chartBuilder/components/legend.spec.ts', LEGEND],
];

/** `file: { test title (or its unique start): reason }`. Reasons are written into the file. */
const SKIP: Record<string, Record<string, string>> = {};

/**
 * `file: [v12's text, v13's, reason]`: an expectation v13 changes on purpose, each text found
 * exactly once. Reasons are written into the file.
 */
const REWRITE: Record<string, readonly (readonly [string, string, string])[]> = {
  'xychart.jison.spec.ts': [
    [
      "{ text: 'cat2asdf', type: 'text' }",
      "{ text: 'cat2 asdf', type: 'text' }",
      "12.2.0 joined unquoted words (`cat2asdf`); v13 keeps one space between them, as v12's fix mermaid-js/mermaid#8575 does (#683)",
    ],
  ],
};

/** v12's error text in a `toThrowError` check: v13 has its own messages (R-ERR-5). */
const V12_MESSAGE = /\.toThrowError\(\s*(["'`])(?:(?!\1)[^\\]|\\.)*\1\s*\)/g;

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

let total = 0;
let skipped = 0;
for (const [file, imports] of FILES) {
  const name = file.slice(file.lastIndexOf('/') + 1);
  let body = git('show', `${V12}:${DIR}/${file}`)
    // Imports, a multi-line one included: the adapter's import replaces them.
    .replace(/^import\b[^;]*?\bfrom ['"][^'"]+['"];?$/gm, '')
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line) && !line.startsWith('// @ts-ignore'))
    .join('\n');
  const notes: string[] = [];
  body = body.replace(V12_MESSAGE, () => {
    notes.push("// rewritten: a check of v12's error text keeps only the rejection (R-ERR-5)");
    return '.toThrowError()';
  });
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${DIR}/${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    "import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';",
    imports,
    ...new Set(notes),
    '',
  ].join('\n');
  writeFileSync(join(OUT, name), header + body);
}
// The expectations v13 changes on purpose, each with its note under the imports.
for (const [name, edits] of Object.entries(REWRITE)) {
  const path = join(OUT, name);
  let text = readFileSync(path, 'utf8');
  for (const [from, to, reason] of edits) {
    if (text.split(from).length !== 2) throw new Error(`${name}: ${from} is not there once`);
    const note = `// rewritten: ${from} as ${to}, ${reason}`;
    text = text.replace(from, to).replace('\n\n', `\n${note}\n\n`);
  }
  writeFileSync(path, text);
}
process.stdout.write(`${FILES.length} files, ${total} tests (${skipped} skipped)\n`);
