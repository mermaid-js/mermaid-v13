/**
 * Ports v12's event modeling specs (R-TEST-3) into `src/v12-specs/`, run against v13's parser
 * through `src/v12-specs/adapter.ts`: v12's event modeling `parser`, DB (`getState()`) and
 * `mermaidAPI.parse` for the diagram spec and `parser.ts`'s in-source test, and Langium's
 * `parse` result and the validator for the parser package's spec. The spec bodies are copied
 * unchanged from the last v12 commit; only imports are rewritten, and tests listed in `SKIP`
 * (with a reason) are turned into `it.skip` / `describe.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-eventmodeling port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const V12 = 'fa796a943';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));

interface Source {
  /** Path at {@link V12}. */
  file: string;
  /** File name in `src/v12-specs/`. */
  name: string;
  /** The imports that replace the spec's own. */
  imports: string[];
  /** Only the `if (import.meta.vitest) { … }` block of a source file. */
  inSource?: boolean;
}

const SOURCES: Source[] = [
  {
    file: 'packages/mermaid/src/diagrams/eventmodeling/eventmodeling.spec.ts',
    name: 'eventmodeling.spec.ts',
    imports: [
      "import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';",
      "import { db, mermaidAPI, parser, SVGElement } from './adapter.ts';",
    ],
  },
  {
    file: 'packages/mermaid/src/diagrams/eventmodeling/parser.ts',
    name: 'parser.spec.ts',
    imports: [
      "import { describe, expect, it } from 'vitest';",
      "import { parser } from './adapter.ts';",
    ],
    inSource: true,
  },
  {
    file: 'packages/parser/tests/eventmodeling.test.ts',
    name: 'langium-eventmodeling.spec.ts',
    imports: [
      "import { assert, describe, expect, it } from 'vitest';",
      "import { eventModelingParse as parse, EventModelingValidator, registerValidationChecks } from './adapter.ts';",
    ],
  },
];

/** `file name: { test title (or its unique start): reason }`. Reasons are written into the file. */
export const SKIP: Record<string, Record<string, string>> = {
  'langium-eventmodeling.spec.ts': {
    'registers checks against the validation registry':
      "Langium's service wiring: v13 has no validation registry. v12's validator never ran in its render (`parse()` skipped validation, so mermaid@12 accepts `evt ->> evt`); v13 runs its checks in the parser as the `EVENTMODELING_INVALID_SOURCE` warning (D525), which the other validator tests check through the adapter.",
  },
};

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

/** The body of a source file's `if (import.meta.vitest) { … }` block, without its destructuring. */
function inSourceBlock(text: string): string {
  const open = text.indexOf('if (import.meta.vitest) {');
  const close = text.lastIndexOf('}');
  if (open < 0 || close < open) throw new Error('no in-source test block');
  return text
    .slice(text.indexOf('\n', open) + 1, close)
    .split('\n')
    .filter((line) => !line.includes('import.meta.vitest'))
    .join('\n');
}

let total = 0;
let skipped = 0;
for (const { file, name, imports, inSource } of SOURCES) {
  const text = git('show', `${V12}:${file}`);
  let body = (inSource ? inSourceBlock(text) : text)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line))
    .join('\n');
  // Multi-line imports.
  body = body.replace(/^import (?:type )?\{[^}]*\} from ['"][^'"]+['"];\n/gm, '');
  const notes: string[] = [];
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip|\.each\([^)]*\))?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${file}${inSource ? ' (its in-source test)' : ''}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    ...imports,
    ...notes,
    '',
  ].join('\n');
  writeFileSync(join(OUT, name), header + body);
}
process.stdout.write(`${SOURCES.length} files, ${total} tests (${skipped} skipped)\n`);
