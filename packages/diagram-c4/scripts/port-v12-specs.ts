/**
 * Ports v12's C4 parser specs (R-TEST-3) into `src/v12-specs/`, run against v13's parser
 * through `src/v12-specs/adapter.ts`: `c4.parser.parse` parses with v13 and `c4Db` reads the
 * model back in v12's DB shapes. The spec bodies are copied unchanged from `fa796a943`
 * (byte-identical to mermaid\@12.2.0's C4 sources); only imports are rewritten, and tests listed
 * in `SKIP` (with a reason) are turned into `it.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-c4 port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The last v12 commit of the C4 sources (byte-identical to 12.2.0, spec #522). */
const V12 = 'fa796a943';
const DIR = 'packages/mermaid/src/diagrams/c4/parser';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));
const FILES = [
  'c4Boundary.spec.ts',
  'c4Component.spec.ts',
  'c4Container.spec.ts',
  'c4Diagram.spec.ts',
  'c4NamedAttributes.spec.ts',
  'c4Person.spec.ts',
  'c4PersonExt.spec.ts',
  'c4System.spec.ts',
];

/**
 * D452: a named argument in the label slot sets the field it names, and the label is empty
 * (`C4_NAMED_ARGUMENT_MOVED`); v12 stored the raw argument as the label (`label.text` an object),
 * which these tests assert.
 */
const NAMED_IN_LABEL =
  'D452: `$name="…"` in the label slot sets that field and leaves the label empty (v12 stored it as `label.text`)';
const LABEL_SLOT = {
  'should parse a sprite': NAMED_IN_LABEL,
  'should parse a link': NAMED_IN_LABEL,
  'should parse tags': NAMED_IN_LABEL,
};

/** `file: { test title (or its unique start): reason }`. Reasons are written into the file. */
const SKIP: Record<string, Record<string, string>> = {
  'c4Boundary.spec.ts': {
    'should parse a link': NAMED_IN_LABEL,
    'should parse tags': NAMED_IN_LABEL,
  },
  'c4Container.spec.ts': LABEL_SLOT,
  'c4Person.spec.ts': LABEL_SLOT,
  'c4PersonExt.spec.ts': LABEL_SLOT,
  'c4System.spec.ts': LABEL_SLOT,
};

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

let total = 0;
let skipped = 0;
for (const file of FILES) {
  let body = git('show', `${V12}:${DIR}/${file}`)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line) && !line.startsWith('// @ts-ignore'))
    .join('\n');
  const notes: string[] = [];
  for (const [title, reason] of Object.entries(SKIP[file] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${file}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip|\.each\([^)]*\))?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}, byte-identical to 12.2.0), ${DIR}/${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    "import { beforeEach, describe, expect, it } from 'vitest';",
    "import { c4, c4Db, setConfig } from './adapter.ts';",
    ...new Set(notes),
    '',
  ].join('\n');
  writeFileSync(join(OUT, file), header + body);
}
process.stdout.write(`${FILES.length} files, ${total} tests (${skipped} skipped)\n`);
