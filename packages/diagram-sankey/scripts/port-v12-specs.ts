/**
 * Ports v12's sankey parser spec (R-TEST-3) into `src/v12-specs/`, run against v13's parser
 * through `src/v12-specs/adapter.ts`: `sankey.parser.parse` parses with v13 and `db` reads the
 * model back in v12's shapes. The spec body is copied unchanged from mermaid\@12.2.0, with the
 * `energy.csv` it reads; only imports are rewritten (`fs` and `path` are Node's, `__dirname`
 * this folder), and tests listed in `SKIP` (with a reason) are turned into `it.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-sankey port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** mermaid\@12.2.0 (the tag is not in this repository; see `v13/docs/agents/runs/427`). */
const V12 = '1fb786986';
const DIR = 'packages/mermaid/src/diagrams/sankey/parser';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));
const FILES = ['sankey.spec.ts'];
/** Fixtures the specs read, copied as they are. */
const DATA = ['energy.csv'];

/**
 * `file: { test title (or its unique start): { reason, divergence } }`, in `v12-skips.json`.
 * Reasons are written into the file. Each skip names the parity divergence that is its cause
 * (an id in `packages/conformance/divergences/<type>.json`): the port refuses a skip whose divergence
 * is not listed, and `conformance/src/sankey/v12-skips.spec.ts` checks the same on every run,
 * so a skip cannot outlive its divergence. The oracle (12.2.0) parses `__proto__,A` /
 * `A,__proto__`, a cycle that v12's d3-sankey then refuses at render; v13 rejects it at parse
 * (D393), so the two tests that parse it are skipped.
 */
const SKIP = JSON.parse(
  readFileSync(new URL('./v12-skips.json', import.meta.url), 'utf8')
) as Record<string, Record<string, { reason: string; divergence: string }>>;
/** The parity divergence ids: every `packages/conformance/divergences/<type>.json`. */
const DIVERGENCES_DIR = join(ROOT, 'packages/conformance/divergences');
const DIVERGENCES = new Set(
  readdirSync(DIVERGENCES_DIR)
    .filter((f) => f.endsWith('.json'))
    .flatMap((f) => JSON.parse(readFileSync(join(DIVERGENCES_DIR, f), 'utf8')) as { id: string }[])
    .map((d) => d.id)
);

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

let total = 0;
let skipped = 0;
for (const file of DATA) writeFileSync(join(OUT, file), git('show', `${V12}:${DIR}/${file}`));
for (const file of FILES) {
  let body = git('show', `${V12}:${DIR}/${file}`)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line) && !line.startsWith('// @ts-'))
    .join('\n');
  const notes: string[] = [];
  for (const [title, { reason, divergence }] of Object.entries(SKIP[file] ?? {})) {
    if (!DIVERGENCES.has(divergence)) {
      throw new Error(
        `${file}: the skip of ${title} names ${divergence}, which is not a divergence`
      );
    }
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${file}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}, 12.2.0), ${DIR}/${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    "import * as fs from 'node:fs';",
    "import * as path from 'node:path';",
    "import { fileURLToPath } from 'node:url';",
    "import { beforeEach, describe, expect, it } from 'vitest';",
    "import { cleanupComments, db, prepareTextForParsing, sankey } from './adapter.ts';",
    'const __dirname = path.dirname(fileURLToPath(import.meta.url));',
    ...new Set(notes),
    '',
  ].join('\n');
  writeFileSync(join(OUT, file), header + body);
}
process.stdout.write(`${FILES.length} files, ${total} tests (${skipped} skipped)\n`);
