/**
 * Ports v12's block parser and DB specs (R-TEST-3) into `src/v12-specs/`, run against v13's
 * parser through `src/v12-specs/adapter.ts`: `block.parse` parses with v13 and `db` reads the
 * model back in v12's shapes. The spec bodies are copied unchanged from mermaid\@12.2.0; only
 * imports are rewritten, and tests listed in `SKIP` (with a reason) are turned into `it.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-block port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** mermaid\@12.2.0 (the tag is not in this repository; see `v13/docs/agents/runs/424`). */
const V12 = '1fb786986';
const DIR = 'packages/mermaid/src/diagrams/block';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));
/** v12 path under `DIR` → the file written. */
const FILES: Record<string, string> = {
  'parser/block.spec.ts': 'block.spec.ts',
  'blockDB.spec.ts': 'blockDB.spec.ts',
  'blockColorIndex.spec.ts': 'blockColorIndex.spec.ts',
};

const RENDER =
  "the stylesheet is render-side (v12 `styles.ts`): v13 draws composites' palette slots without CSS (#556)";

/** `file: { test title (or its unique start): reason }`. Reasons are written into the file. */
const SKIP: Record<string, Record<string, string>> = {
  'parser/block.spec.ts': {
    'sanitizes labels with the current dompurify config':
      'v13 keeps labels as written and escapes them when it writes the SVG; nothing is sanitised at parse',
    'should log a warning when block width exceeds column width':
      "v13's parser has no logger; a span wider than the grid is laid out as v12 lays it out (#555)",
  },
  'blockDB.spec.ts': {
    'block db runtime config':
      'v13 reads no config while it parses (the model holds labels as written)',
  },
  'blockColorIndex.spec.ts': {
    'emits one composite rule per palette entry under a colour theme': RENDER,
    'leaves the simple shapes to the flat theme colour': RENDER,
    'emits nothing for a theme that carries no palette': RENDER,
    'rejects a look that would break out of the selector': RENDER,
  },
};

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

let total = 0;
let skipped = 0;
for (const [file, out] of Object.entries(FILES)) {
  let body = git('show', `${V12}:${DIR}/${file}`)
    .split('\n')
    .filter(
      (line) => !/^import .* from ['"]/.test(line) && !/^\/\/ @ts-(ignore|expect-error)/.test(line)
    )
    .join('\n');
  const notes: string[] = [];
  for (const [title, reason] of Object.entries(SKIP[file] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${file}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}, 12.2.0), ${DIR}/${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    "import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';",
    "import { block, configApi, db, diagramAPI, log } from './adapter.ts';",
    ...new Set(notes),
    '',
  ].join('\n');
  writeFileSync(join(OUT, out), header + body);
}
process.stdout.write(`${Object.keys(FILES).length} files, ${total} tests (${skipped} skipped)\n`);
