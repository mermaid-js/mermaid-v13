/**
 * Ports v12's requirement parser spec (R-TEST-3) into `src/v12-specs/`, run against v13's parser
 * through `src/v12-specs/adapter.ts`: `reqDiagram.parser.parse` parses with v13 and the
 * `RequirementDB` reads the model back in v12's shapes. The spec body is copied unchanged from
 * mermaid\@12.2.0; only imports are rewritten (the adapter stands in for v12's config, DB and
 * jison parser), and tests listed in `SKIP` (with a reason) are turned into `it.skip`.
 *
 * `requirementDb.spec.ts` called the DB directly; it is ported by hand as model-builder tests
 * (`src/parser/builder.spec.ts`).
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-requirement port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** mermaid\@12.2.0 (the tag is not in this repository; see `v13/docs/agents/runs/427`). */
const V12 = '1fb786986';
const DIR = 'packages/mermaid/src/diagrams/requirement/parser';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));
/** Source file → ported file (a `.js` spec becomes `.ts`). */
const FILES: Record<string, string> = {
  'requirementDiagram.spec.js': 'requirementDiagram.spec.ts',
};

/**
 * `file: { test title (or its unique start): reason }`. Reasons are written into the file. The
 * oracle (12.2.0) passes all of v12's tests, and so does v13: nothing is skipped.
 */
const SKIP: Record<string, Record<string, string>> = {};

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

let total = 0;
let skipped = 0;
for (const [file, out] of Object.entries(FILES)) {
  let body = git('show', `${V12}:${DIR}/${file}`)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line) && !line.startsWith('// @ts-'))
    .join('\n');
  const notes: string[] = [];
  for (const [title, reason] of Object.entries(SKIP[file] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${file}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe|test(?:\.each\([^)]*\)))\.skip/g) ?? []).length;
  total += (body.match(/\b(?:it(?:\.skip)?\(|test\.each\()/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}, 12.2.0), ${DIR}/${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    "import { beforeEach, describe, expect, it, test } from 'vitest';",
    "import { RequirementDB, reqDiagram, setConfig } from './adapter.ts';",
    ...new Set(notes),
    '',
  ].join('\n');
  writeFileSync(join(OUT, out), header + body);
}
process.stdout.write(`${Object.keys(FILES).length} files, ${total} tests (${skipped} skipped)\n`);
