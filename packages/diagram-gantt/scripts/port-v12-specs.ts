/**
 * Ports v12's gantt parser spec (R-TEST-3) into `src/v12-specs/`, run against v13's parser
 * through `src/v12-specs/adapter.ts`: `parser.parse` parses with v13 and replays the statements
 * as v12's DB calls, and `ganttDb` reads the model back in v12's shapes. The spec bodies are copied unchanged from the
 * last v12 commit; only imports are rewritten, and tests listed in `SKIP` (with a reason) are
 * turned into `it.skip`.
 *
 * Usage: `pnpm --filter @mermaid-js/diagram-gantt port:v12-specs` (also runs prettier).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const V12 = 'fa796a943';
const DIR = 'packages/mermaid/src/diagrams/gantt';
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/v12-specs/', import.meta.url));
const FILES = ['parser/gantt.spec.js'];
/** Output file names, by source file. */
const OUT_NAMES: Record<string, string> = { 'parser/gantt.spec.js': 'gantt.spec.ts' };

/** `file: { test title (or its unique start): reason }`. Reasons are written into the file. */
const SKIP: Record<string, Record<string, string>> = {};

const git = (...args: string[]) =>
  execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', maxBuffer: 1 << 26 });

let total = 0;
let skipped = 0;
for (const file of FILES) {
  const name = OUT_NAMES[file] ?? file.replace(/\.js$/, '.ts');
  let body = git('show', `${V12}:${DIR}/${file}`)
    .split('\n')
    .filter((line) => !/^import .* from ['"]/.test(line))
    .join('\n');
  const notes: string[] = [];
  for (const [title, reason] of Object.entries(SKIP[name] ?? {})) {
    let hit = 0;
    body = body.replace(
      /\b(it|describe)\((['"`])((?:(?!\2)[^\\]|\\.)*)\2/g,
      (m, fn: string, q: string, t: string) => {
        if (!t.replace(/\\(.)/g, '$1').startsWith(title)) return m;
        hit++;
        return `${fn}.skip(${q}${t}${q}`;
      }
    );
    if (hit === 0) throw new Error(`${name}: no test titled ${title}`);
    notes.push(`// skipped: ${title} — ${reason}`);
  }
  skipped += (body.match(/\b(?:it|describe)\.skip/g) ?? []).length;
  total += (body.match(/\bit(?:\.skip)?\(/g) ?? []).length;
  const header = [
    '/* eslint-disable */',
    `// Ported from mermaid v12 (${V12}), ${DIR}/${file}.`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.',
    '// Generated by scripts/port-v12-specs.ts: edit SKIP there, not this file.',
    '// @ts-nocheck',
    '// cspell:disable',
    "import { beforeEach, describe, expect, it, vi } from 'vitest';",
    "import { ganttDb, parser } from './adapter.ts';",
    ...new Set(notes),
    '',
  ].join('\n');
  writeFileSync(join(OUT, name), header + body);
}
process.stdout.write(`${FILES.length} files, ${total} tests (${skipped} skipped)\n`);
