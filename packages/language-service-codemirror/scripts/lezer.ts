/**
 * Builds the CodeMirror Lezer parser from gen-grammar's generated highlighting grammar
 * (`packages/diagram-flowchart/grammar/generated/flowchart.grammar`, #21) with
 * lezer-generator. `pnpm --filter @mermaid-js/language-service-codemirror gen` writes the
 * output to `src/generated/`; `src/generated.spec.ts` fails when it is stale.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildParserFile } from '@lezer/generator';

const ROOT = join(import.meta.dirname, '..', '..', '..');
export const GRAMMAR_DIR = join(ROOT, 'packages/diagram-flowchart/grammar/generated');
export const OUT_DIR = join(import.meta.dirname, '..', 'src', 'generated');

const HEADER =
  '// Generated by packages/language-service-codemirror/scripts/generate.ts from\n' +
  '// packages/diagram-flowchart/grammar/generated/flowchart.grammar. Do not edit.\n';

/** File name in `src/generated/` → contents. */
export function lezerFiles(): Map<string, string> {
  const grammar = readFileSync(join(GRAMMAR_DIR, 'flowchart.grammar'), 'utf8');
  const tokens = readFileSync(join(GRAMMAR_DIR, 'flowchart.tokens.js'), 'utf8');
  const built = buildParserFile(grammar, { fileName: 'flowchart.grammar', moduleStyle: 'es' });
  return new Map([
    ['flowchart.parser.js', HEADER + built.parser],
    ['flowchart.parser.terms.js', HEADER + built.terms],
    ['flowchart.tokens.js', tokens],
    [
      'flowchart.parser.d.ts',
      HEADER +
        "import type { LRParser } from '@lezer/lr';\n\nexport declare const parser: LRParser;\n",
    ],
  ]);
}
