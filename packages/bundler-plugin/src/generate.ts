/// <reference types="node" />
/**
 * The generated `mermaid/discovered` module (D164): the build-time scan of the bundler's
 * project root (`mermaid/node-scan`, T4's rules and confinement, D165) as ES module text. Each
 * diagram's detector is imported statically, since detection needs it before any render;
 * each entry (and ascii entry) is a dynamic `import()`, so the bundler splits it into a chunk
 * that loads on first detection. Extension entries are dynamic too and load on the API's first
 * use (D169). Order and collisions are left to the registry (D166): the list is in package
 * order and `addDiscovered` sorts it anyway. Scan warnings are build-time only (the bundler
 * warns): nothing machine-specific goes into the bundle.
 *
 * Detectors are evaluated while `mermaid` itself is, so a detector must not import `mermaid`.
 *
 * Layout manifests (#238) are skipped by the scan until `readManifest` accepts them. Their arm
 * is one more case in `entryOf`: a `layout` entry with the manifest's names and a loader that
 * imports the entry lazily and takes its `export` (default `default`), plus a static import of
 * an eager `config` module when the manifest has one.
 */
import { readdir } from 'node:fs/promises';
import { join, relative, win32 } from 'node:path';
import { FIRST_PARTY_IDS, findAppRoot, scanPlugins, type ScannedPackage } from 'mermaid/node-scan';

export interface DiscoveredModule {
  /** The module text that replaces `mermaid/discovered`. */
  readonly code: string;
  /** Build warnings: packages the scan skipped, paths relative to the app root. */
  readonly warnings: readonly string[];
  /** The app root the scan used, or undefined when no package.json was found. */
  readonly root: string | undefined;
  /**
   * What the result depends on, for watch mode and persistent caches: the app's package.json,
   * the package managers' install markers in `node_modules` (rewritten on every install or
   * removal), and each found plugin's package.json.
   */
  readonly watchFiles: readonly string[];
  /** `node_modules` and its `@scope` folders (a package added or removed changes them). */
  readonly watchDirs: readonly string[];
}

/** Files a package manager rewrites in `node_modules` on every install or removal. */
export const INSTALL_MARKERS: readonly string[] = [
  '.package-lock.json',
  '.modules.yaml',
  '.yarn-state.yml',
  '.yarn-integrity',
];

/**
 * A module specifier for an absolute file path. POSIX paths as they are; Windows drive paths
 * with forward slashes (`C:/app/x.js`, which every bundler resolves); UNC and `\\?\` paths
 * keep their backslashes, since `//server/share` would read as a protocol-relative URL.
 */
export function specifierOf(path: string): string {
  if (path.startsWith('\\\\')) return path;
  if (win32.isAbsolute(path) && /^[A-Za-z]:/.test(path)) return path.replaceAll('\\', '/');
  return path;
}

const spec = (path: string): string => JSON.stringify(specifierOf(path));

/**
 * The manifest as an expression that yields exactly what `readManifest` saw: a JSON.parse of
 * its JSON, so a `__proto__` key stays an own property instead of setting the prototype.
 */
const manifestOf = (raw: unknown): string => `JSON.parse(${JSON.stringify(JSON.stringify(raw))})`;

/** The list entry of one package, and the static imports it needs. */
function entryOf(p: ScannedPackage, index: number): { imports: string[]; expr: string } {
  const head = `kind: "plugin", package: ${JSON.stringify(p.package)}`;
  const manifest = `manifest: ${manifestOf(p.raw)}`;
  const load = `load: () => import(${spec(p.files.entry)})`;
  if (p.manifest.plugin === 'extension')
    return { imports: [], expr: `{ ${head}, plugin: { ${manifest}, ${load} } }` };
  const ascii =
    p.files.ascii === undefined ? '' : `, loadAscii: () => import(${spec(p.files.ascii)})`;
  // No detector path: the registry skips the package with its own PLUGIN_SKIPPED message.
  if (p.files.detector === undefined)
    return { imports: [], expr: `{ ${head}, plugin: { ${manifest}, ${load}${ascii} } }` };
  const name = `detector${index}`;
  return {
    imports: [`import * as ${name} from ${spec(p.files.detector)};`],
    expr: `{ ${head}, plugin: { ${manifest}, detector: pick(${name}), ${load}${ascii} } }`,
  };
}

/** The module for `packages`. */
function render(packages: readonly ScannedPackage[]): string {
  const entries = packages.map(entryOf);
  return [
    "// Generated by @mermaid-js/bundler-plugin (D164): the plugins in the app's node_modules.",
    ...entries.flatMap((e) => e.imports),
    // The detector module's `detector` or default export; a non-function makes the registry
    // skip the package (PLUGIN_SKIPPED). Taking the namespace as a value keeps bundlers from
    // warning about a missing named export.
    'const pick = (m) => { const f = m.detector ?? m.default; return typeof f === "function" ? f : undefined; };',
    `export default [${entries.map((e) => `\n  ${e.expr},`).join('')}\n];`,
    '',
  ].join('\n');
}

/** `message` with the app root written as `.`, so no build-machine path is reported. */
function rootRelative(message: string, root: string): string {
  return message.replaceAll(root, '.');
}

/** `node_modules` and its `@scope` folders, as far as they exist. */
async function moduleDirs(root: string): Promise<string[]> {
  const modules = join(root, 'node_modules');
  try {
    const entries = await readdir(modules, { withFileTypes: true });
    return [
      modules,
      ...entries
        .filter((e) => e.name.startsWith('@') && (e.isDirectory() || e.isSymbolicLink()))
        .map((e) => join(modules, e.name)),
    ];
  } catch {
    return [];
  }
}

/**
 * Scans the app whose package.json is at or above `projectRoot` (the bundler's root) and
 * returns the `mermaid/discovered` module for it. Never throws for a package's sake.
 */
export async function discoveredModule(projectRoot: string): Promise<DiscoveredModule> {
  const root = await findAppRoot(projectRoot);
  if (root === undefined)
    return { code: render([]), warnings: [], root, watchFiles: [], watchDirs: [] };
  const { packages, warnings } = await scanPlugins(root, { firstPartyIds: FIRST_PARTY_IDS });
  const messages = warnings.map((w) => rootRelative(w.message, root));
  for (const p of packages)
    if (p.files.detector !== undefined && p.files.detector === p.files.entry)
      messages.push(
        `${p.package}: its detector and entry are the same file (${relative(root, p.files.entry)}), so the whole diagram is bundled eagerly; give the detector its own module`
      );
  const watchDirs = await moduleDirs(root);
  const watchFiles = [
    join(root, 'package.json'),
    ...INSTALL_MARKERS.map((m) => join(root, 'node_modules', m)),
    ...packages.map((p) => join(p.dir, 'package.json')),
  ];
  return { code: render(packages), warnings: messages, root, watchFiles, watchDirs };
}
