/// <reference types="node" />
/**
 * The generated `mermaid/discovered` module (D164): the build-time scan of the bundler's
 * project root (`mermaid/node-scan`, T4's rules and confinement, D165) as ES module text. Each
 * diagram's detector is imported statically, since detection needs it before any render;
 * each entry (and ascii entry) is a dynamic `import()`, so the bundler splits it into a chunk
 * that loads on first detection. Extension entries are dynamic too and load on the API's first
 * use (D169). Order and collisions are left to the registry (D166): the list is in package
 * order and `addDiscovered` sorts it anyway.
 *
 * Layout manifests (#238) are skipped by the scan until `readManifest` accepts them. Their arm
 * is one more case in `entryOf`: a `layout` entry with the manifest's names and a loader that
 * imports the entry lazily and takes its `export` (default `default`), plus a static import of
 * an eager `config` module when the manifest has one.
 */
import {
  FIRST_PARTY_IDS,
  findAppRoot,
  scanPlugins,
  type ScannedPackage,
  type ScanWarning,
} from 'mermaid/node-scan';

export interface DiscoveredModule {
  /** The module text that replaces `mermaid/discovered`. */
  readonly code: string;
  /** The scan's warnings (skipped packages), also exported as `warnings` for the first render. */
  readonly warnings: readonly ScanWarning[];
  /** The app root the scan used, or undefined when no package.json was found. */
  readonly root: string | undefined;
}

/** A module specifier for an absolute file path (forward slashes, also on Windows). */
const spec = (path: string): string => JSON.stringify(path.replaceAll('\\', '/'));

/** The list entry of one package, and the static imports it needs. */
function entryOf(p: ScannedPackage, index: number): { imports: string[]; expr: string } {
  const head = `kind: "plugin", package: ${JSON.stringify(p.package)}`;
  const manifest = `manifest: ${JSON.stringify(p.raw)}`;
  const load = `load: () => import(${spec(p.files.entry)})`;
  if (p.manifest.plugin === 'extension')
    return { imports: [], expr: `{ ${head}, plugin: { ${manifest}, ${load} } }` };
  const ascii =
    p.files.ascii === undefined ? '' : `, loadAscii: () => import(${spec(p.files.ascii)})`;
  // No detector path: the registry skips the package with its own PLUGIN_SKIPPED message.
  if (p.files.detector === undefined)
    return { imports: [], expr: `{ ${head}, plugin: { ${manifest}, ${load}${ascii} } }` };
  const name = `detector${index}`;
  return {
    imports: [`import * as ${name} from ${spec(p.files.detector)};`],
    expr: `{ ${head}, plugin: { ${manifest}, detector: pick(${name}), ${load}${ascii} } }`,
  };
}

/** The module for `packages` and `warnings`. */
function render(packages: readonly ScannedPackage[], warnings: readonly ScanWarning[]): string {
  const entries = packages.map(entryOf);
  return [
    "// Generated by @mermaid-js/bundler-plugin (D164): the plugins in the app's node_modules.",
    ...entries.flatMap((e) => e.imports),
    // The detector module's `detector` or default export; a non-function makes the registry
    // skip the package (PLUGIN_SKIPPED). Taking the namespace as a value keeps bundlers from
    // warning about a missing named export.
    'const pick = (m) => { const f = m.detector ?? m.default; return typeof f === "function" ? f : undefined; };',
    `export default [${entries.map((e) => `\n  ${e.expr},`).join('')}\n];`,
    `export const warnings = ${JSON.stringify(warnings)};`,
    '',
  ].join('\n');
}

/**
 * Scans the app whose package.json is at or above `projectRoot` (the bundler's root) and
 * returns the `mermaid/discovered` module for it. Never throws for a package's sake.
 */
export async function discoveredModule(projectRoot: string): Promise<DiscoveredModule> {
  const root = await findAppRoot(projectRoot);
  if (root === undefined) return { code: render([], []), warnings: [], root };
  const { packages, warnings } = await scanPlugins(root, { firstPartyIds: FIRST_PARTY_IDS });
  return { code: render(packages, warnings), warnings, root };
}
