/**
 * Copies gen-grammar's generated Monarch files
 * (`packages/diagram-<id>/grammar/generated/<id>.monarch.json`, #21) into this adapter as
 * modules (D134, D135): the diagram packages publish no generated grammar output (D54), so
 * the adapter ships its own copy.
 * `pnpm --filter @mermaid-js/language-service-monaco gen` writes them to `src/generated/`,
 * and the `MONARCH_HIGHLIGHTERS` map at the end of `src/grammars.ts`, one row per file;
 * `src/generated.spec.ts` fails when either is stale.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { highlighted, ROOT, withMap } from './highlighted.ts';

export const OUT_DIR = join(import.meta.dirname, '..', 'src', 'generated');
export const GRAMMARS_MODULE = join(import.meta.dirname, '..', 'src', 'grammars.ts');

/**
 * The highlighted types (`scripts/highlighted.ts`): each diagram package whose manifest has a
 * `language` entry. The files here are named after the facet id, and so is the token postfix
 * (`.mermaid-<id>`), which says which type's grammar coloured a token; the package's grammar
 * files are named after its directory (`quadrant` for `quadrantChart`, #317).
 */
export const HIGHLIGHTED = highlighted();

const header = (type: string) =>
  '// Generated by packages/language-service-monaco/scripts/generate.ts from\n' +
  `// packages/diagram-${type}/grammar/generated/${type}.monarch.json. Do not edit.\n`;

/** File name in `src/generated/` → contents. */
export function monarchFiles(): Map<string, string> {
  const files = new Map<string, string>();
  for (const { id, type } of HIGHLIGHTED) {
    const json = readFileSync(
      join(ROOT, `packages/diagram-${type}/grammar/generated/${type}.monarch.json`),
      'utf8'
    );
    // Re-serialised, so the module is the definition whatever the JSON file's layout.
    const parsed = JSON.parse(json) as { tokenPostfix?: string };
    if (type !== id) parsed.tokenPostfix = `.mermaid-${id}`;
    const def = JSON.stringify(parsed, null, 2);
    files.set(`${id}.monarch.js`, `${header(type)}export default ${def};\n`);
    files.set(
      `${id}.monarch.d.ts`,
      header(type) +
        "import type { MonarchDefinition } from '../grammars.ts';\n\n" +
        'declare const monarch: MonarchDefinition;\nexport default monarch;\n'
    );
  }
  return files;
}

const MAP_HEAD =
  'export const MONARCH_HIGHLIGHTERS: Readonly<Record<FirstPartyFacetId, MonarchHighlighter>> =';

/** `src/grammars.ts` (`current`) with its `MONARCH_HIGHLIGHTERS` map rewritten: a row per type. */
export function grammarsModule(current: string = readFileSync(GRAMMARS_MODULE, 'utf8')): string {
  return withMap(
    current,
    MAP_HEAD,
    HIGHLIGHTED,
    (id) => `{ load: () => import('./generated/${id}.monarch.js').then((m) => m.default) }`
  );
}
