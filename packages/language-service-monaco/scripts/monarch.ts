/**
 * Copies gen-grammar's generated Monarch files
 * (`packages/diagram-<id>/grammar/generated/<id>.monarch.json`, #21) into this adapter as
 * modules (D134, D135): the diagram packages publish no generated grammar output (D54), so
 * the adapter ships its own copy.
 * `pnpm --filter @mermaid-js/language-service-monaco gen` writes them to `src/generated/`;
 * `src/generated.spec.ts` fails when they are stale.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { MONARCH_HIGHLIGHTERS } from '../src/grammars.ts';

const ROOT = join(import.meta.dirname, '..', '..', '..');
export const OUT_DIR = join(import.meta.dirname, '..', 'src', 'generated');

/** The diagram ids with a Monarch file: the rows of `MONARCH_HIGHLIGHTERS` (src/grammars.ts). */
export const HIGHLIGHTED_TYPES = Object.keys(MONARCH_HIGHLIGHTERS);

const header = (id: string) =>
  '// Generated by packages/language-service-monaco/scripts/generate.ts from\n' +
  `// packages/diagram-${id}/grammar/generated/${id}.monarch.json. Do not edit.\n`;

/** File name in `src/generated/` → contents. */
export function monarchFiles(): Map<string, string> {
  const files = new Map<string, string>();
  for (const id of HIGHLIGHTED_TYPES) {
    const json = readFileSync(
      join(ROOT, `packages/diagram-${id}/grammar/generated/${id}.monarch.json`),
      'utf8'
    );
    // Re-serialised, so the module is the definition whatever the JSON file's layout.
    const def = JSON.stringify(JSON.parse(json), null, 2);
    files.set(`${id}.monarch.js`, `${header(id)}export default ${def};\n`);
    files.set(
      `${id}.monarch.d.ts`,
      header(id) +
        "import type { MonarchDefinition } from '../grammars.ts';\n\n" +
        'declare const monarch: MonarchDefinition;\nexport default monarch;\n'
    );
  }
  return files;
}
