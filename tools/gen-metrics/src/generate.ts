import { readFace, type Face } from './font.ts';

/** Code points in each table: printable ASCII (0x20–0x7E), then Latin-1 (0xA0–0xFF). */
export const TABLE_CODES: readonly number[] = [
  ...Array.from({ length: 0x7f - 0x20 }, (_, i) => 0x20 + i),
  ...Array.from({ length: 0x100 - 0xa0 }, (_, i) => 0xa0 + i),
];

// Measured as zero-width by the table measurer whatever the font says.
const SOFT_HYPHEN = 0xad;

export interface FamilyFonts {
  /** Lower-case CSS family name, e.g. `trebuchet ms`. */
  family: string;
  regular: Uint8Array;
  bold: Uint8Array;
}

function pack(face: Face, label: string): string {
  let out = '';
  for (const code of TABLE_CODES) {
    const w = code === SOFT_HYPHEN ? 0 : face.advance(code);
    if (w === undefined) throw new Error(`${label} has no glyph for U+${code.toString(16)}`);
    if (w > 1295) throw new Error(`${label}: advance ${w} does not fit two base-36 digits`);
    out += w.toString(36).padStart(2, '0');
  }
  return out;
}

/** Returns the source of `packages/core/src/text/metrics.ts`. */
export function generateMetrics(families: readonly FamilyFonts[]): string {
  const rows = families.map(({ family, regular, bold }) => {
    const r = readFace(regular);
    const b = readFace(bold);
    const { ascent, descent, lineGap } = r.vertical;
    return (
      `  ${/^[a-z]+$/.test(family) ? family : `'${family}'`}: [\n` +
      `    ${ascent},\n    ${descent},\n    ${lineGap},\n` +
      `    '${pack(r, `${family} regular`)}',\n` +
      `    '${pack(b, `${family} bold`)}',\n  ],\n`
    );
  });
  return (
    '// cspell:disable\n' +
    '// Generated by tools/gen-metrics from font files. Do not edit; run\n' +
    '// `pnpm --filter @mermaid-js/gen-metrics generate`.\n' +
    '// Per family: ascent, descent, line gap (thousandths of an em, from hhea), then regular\n' +
    '// and bold advance widths for U+0020–U+007E and U+00A0–U+00FF, two base-36 digits each.\n' +
    'export const FACES: Record<string, readonly [number, number, number, string, string]> = {\n' +
    rows.join('') +
    '};\n'
  );
}
