/**
 * The syntax reference page for a grammar file (DESIGN §4.4): the grammar rules in EBNF with
 * their doc comments, then the tokens and lexer modes.
 */
import type { Expr, Grammar, LexRule } from './ebnf.ts';

/** EBNF text of an expression, as written in grammar files. */
export function ebnfText(e: Expr, top = true): string {
  switch (e.t) {
    case 'sym':
      return e.name;
    case 'seq':
      return e.items.map((x) => ebnfText(x, false)).join(' ');
    case 'alt': {
      const s = e.alts.map((x) => ebnfText(x, false)).join(' | ');
      return top ? s : `( ${s} )`;
    }
    case 'opt':
      return `[ ${ebnfText(e.e)} ]`;
    case 'rep':
      return e.min === 0 ? `{ ${ebnfText(e.e)} }` : `${ebnfText(e.e, false)}+`;
  }
}

const cell = (s: string) => s.replace(/\|/g, '\\|');

function action(r: LexRule): string {
  return r.actions
    .map((a) => (a.mode ? `${a.op}(${a.mode})` : a.op))
    .filter((a) => a !== 'attach-next' && a !== 'attach-prev')
    .join(' ');
}

export function syntaxDoc(g: Grammar, title: string, source: string): string {
  const out: string[] = [];
  out.push(`# ${title}`, '');
  out.push(
    `<!-- Generated by tools/gen-grammar from ${source}. Do not edit: run \`pnpm gen:grammar\`. -->`,
    ''
  );
  if (g.doc) out.push(g.doc, '');
  out.push('## Grammar', '');
  out.push(
    'EBNF: `[ x ]` is optional, `{ x }` repeats zero or more times, `x+` one or more times, `|` separates alternatives. Upper-case names and `subgraph`, `end`, `acc_…`, `direction_…` are tokens (see below). A rule marked `@Type` builds an AST node of that type.',
    ''
  );
  for (const r of g.rules) {
    if (r.doc) out.push(r.doc, '');
    const alts =
      r.body.t === 'alt' ? r.body.alts.map((a) => ebnfText(a, false)) : [ebnfText(r.body)];
    const head = r.ast ? `${r.name} @${r.ast}` : r.name;
    out.push(
      '```ebnf',
      `${head} = ${alts.join(`\n${' '.repeat(head.length + 1)}| `)} ;`,
      '```',
      ''
    );
  }
  out.push('## Tokens', '');
  out.push(
    'The lexer works in modes (`INITIAL` and the ones below). In each mode it tries the rules in this order and takes the first that matches; a rule may push a mode or pop back to the previous one. Rules without a token emit nothing.',
    ''
  );
  out.push(`Modes: ${['INITIAL', ...g.modes].map((m) => `\`${m}\``).join(', ')}.`, '');
  out.push('| Modes | Token | Pattern | Action |', '| --- | --- | --- | --- |');
  for (const r of g.lexRules) {
    const pattern = r.pattern.length > 80 ? `${r.pattern.slice(0, 77)}…` : r.pattern;
    out.push(
      `| ${cell(r.modes.join(', '))} | ${r.name ?? '—'} | \`${cell(pattern)}\` | ${cell(action(r))} |`
    );
  }
  out.push('');
  if (g.triviaRules.length > 0) {
    out.push('Removed before lexing (highlighted only):', '');
    for (const r of g.triviaRules) out.push(`- ${r.name ?? '—'}: \`${cell(r.pattern)}\``);
    out.push('');
  }
  return out.join('\n');
}
