/**
 * Regenerate `packages/core/src/parser-kit/unicode-table.ts` from v12's flow.jison:
 *
 *   git show fa796a943:packages/mermaid/src/diagrams/flowchart/parser/flow.jison > /tmp/flow.jison
 *   pnpm exec tsx tools/gen-grammar/src/gen-unicode.ts /tmp/flow.jison packages/core/src/parser-kit/unicode-table.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { packUnicodeLetters } from './unicode.ts';

const [jisonPath, outPath] = process.argv.slice(2);
if (!jisonPath || !outPath) throw new Error('usage: gen-unicode <flow.jison> <out.ts>');
const packed = packUnicodeLetters(readFileSync(jisonPath, 'utf8'));
writeFileSync(
  outPath,
  `// Generated by tools/gen-grammar/src/gen-unicode.ts from v12 flow.jison (UNICODE_TEXT). Do not edit.\n` +
    `// Format: space-separated base-36 pairs \`gap len\`; see tools/gen-grammar/src/unicode.ts.\n` +
    `export const UNICODE_LETTERS =\n  '${packed}';\n`
);
