/**
 * Everything generated from `packages/core/schema/config.schema.yaml` (DESIGN §9, R-CONF-4):
 * the `MermaidConfig` types, top-level defaults and the key tree in core, each ported
 * diagram's section defaults in its own package, and the config reference / migration docs.
 *
 * `generate()` is pure apart from json-schema-to-typescript: schema text in, files out.
 */
import { compile, type JSONSchema } from 'json-schema-to-typescript';
import {
  annotationErrors,
  annotationOf,
  collectProperties,
  defName,
  isRemoved,
  loadSchema,
  resolveRef,
  type RootSchema,
  type SchemaNode,
} from './schema.ts';

export const SCHEMA_PATH = 'packages/core/schema/config.schema.yaml';
export const CORE_GENERATED = 'packages/core/src/config/generated';
export const REFERENCE_DOC = 'v13/docs/config-reference.md';
export const MIGRATION_DOC = 'v13/docs/MIGRATION.md';
/** The config JSON schema the language service checks front matter against (D96). */
export const SERVICE_SCHEMA = 'packages/language-service/src/generated/config-schema.gen.ts';

/**
 * Config sections that belong to a package other than core. Their defaults are written
 * into the owner's package; a section with no package yet gets no defaults at all
 * (its keys are still known, so they are accepted silently, R-CONF-5).
 */
export const SECTION_OWNERS: Readonly<Record<string, string>> = {
  flowchart: 'packages/diagram-flowchart',
  er: 'packages/diagram-er',
};

export const MIGRATION_BEGIN = '<!-- BEGIN GENERATED CONFIG SECTION: pnpm gen:config -->';
export const MIGRATION_END = '<!-- END GENERATED CONFIG SECTION -->';

const BANNER =
  '// Generated by tools/gen-config from packages/core/schema/config.schema.yaml.\n' +
  '// Do not edit: run `pnpm gen:config`.\n';

/** Root keys that are config sections (a diagram's or a layout plugin's own object). */
export function sectionKeys(root: RootSchema): string[] {
  return Object.entries(root.properties ?? {})
    .filter(([key, node]) => defName(node.$ref) !== undefined || key === 'elk')
    .map(([key]) => key);
}

// ---------------------------------------------------------------------------- defaults

function defaultsOf(root: RootSchema, node: SchemaNode): unknown {
  if (node.default !== undefined) {
    return structuredClone(node.default);
  }
  if (node.$ref !== undefined && defName(node.$ref) === undefined) {
    // `$ref` to another def's property: that property's default.
    return defaultsOf(root, resolveRef(root, node.$ref));
  }
  const props = collectProperties(root, node);
  if (props.size === 0) {
    return undefined;
  }
  const out: Record<string, unknown> = {};
  for (const [key, child] of props) {
    if (isRemoved(child)) {
      continue;
    }
    const value = defaultsOf(root, child);
    if (value !== undefined && value !== null) {
      out[key] = value;
    }
  }
  return Object.keys(out).length > 0 ? out : undefined;
}

function coreDefaults(root: RootSchema): Record<string, unknown> {
  const sections = new Set(sectionKeys(root));
  const out: Record<string, unknown> = {};
  for (const [key, node] of Object.entries(root.properties ?? {})) {
    if (sections.has(key) || isRemoved(node)) {
      continue;
    }
    const value = defaultsOf(root, node);
    if (value !== undefined && value !== null) {
      out[key] = value;
    }
  }
  return out;
}

// ---------------------------------------------------------------------------- key tree

/** `0` = a known leaf, `'open'` = an object whose keys are free (themeVariables, dictionaries). */
function keyTreeSource(root: RootSchema): string {
  const defs = new Map<string, string>(); // def name -> emitted const source
  const order: string[] = [];
  const pending = new Set<string>();

  const constName = (name: string) => `D_${name}`;

  const emitDef = (name: string): string => {
    if (!defs.has(name)) {
      if (pending.has(name)) {
        throw new Error(`cyclic $ref through ${name}`);
      }
      pending.add(name);
      const def = root.$defs[name];
      if (def === undefined) {
        throw new Error(`unknown def ${name}`);
      }
      defs.set(name, objectTree(def));
      pending.delete(name);
      order.push(name);
    }
    return constName(name);
  };

  const objectTree = (node: SchemaNode): string => {
    const parts: string[] = [];
    for (const part of node.allOf ?? []) {
      const name = defName(part.$ref);
      if (name === undefined) {
        throw new Error('allOf entries must $ref a whole def');
      }
      parts.push(`...${emitDef(name)}`);
    }
    for (const [key, child] of Object.entries(node.properties ?? {})) {
      parts.push(`${JSON.stringify(key)}: ${tree(child)}`);
    }
    return `{ ${parts.join(', ')} }`;
  };

  const tree = (node: SchemaNode): string => {
    const status = annotationOf(node).status;
    if (status === 'removed' || status === 'moved') {
      return JSON.stringify(status);
    }
    const whole = defName(node.$ref);
    if (whole !== undefined) {
      const target = root.$defs[whole];
      return target && collectProperties(root, target).size > 0 ? emitDef(whole) : leaf(target);
    }
    if (node.$ref !== undefined) {
      return tree({ ...resolveRef(root, node.$ref), 'x-mermaid': node['x-mermaid'] });
    }
    // Named properties with `additionalProperties` are documentation only: any key is
    // accepted, so the object stays open (e.g. `themeVariables`, R-CONF-5).
    if (node.additionalProperties !== undefined && node.additionalProperties !== false) {
      return '"open"';
    }
    if (node.properties !== undefined || node.allOf !== undefined) {
      return objectTree(node);
    }
    return leaf(node);
  };

  const leaf = (node: SchemaNode | undefined): string => {
    const types = node?.type === undefined ? [] : [node.type].flat();
    return types.length > 0 && !types.includes('object') ? '0' : '"open"';
  };

  const rootTree = objectTree(root);
  const lines = [
    BANNER,
    "import type { KeyNote, KeyTree } from '../keys.ts';",
    '',
    ...order.map((name) => `const ${constName(name)}: KeyTree = ${defs.get(name)};`),
    '',
    '/** Every config key the schema declares, for unknown-key and removed-key warnings. */',
    `export const KEY_TREE: KeyTree = ${rootTree};`,
    '',
    '/** What a removed or moved key turned into, by dotted path. */',
    `export const KEY_NOTES: Readonly<Record<string, KeyNote>> = ${JSON.stringify(keyNotes(root), null, 2)};`,
    '',
  ];
  return lines.join('\n');
}

/** Removed and moved keys reachable from the root, by dotted path. */
function keyNotes(root: RootSchema): Record<string, unknown> {
  const notes: Record<string, unknown> = {};
  const walk = (node: SchemaNode, path: string, depth: number) => {
    if (depth > 8) {
      return;
    }
    for (const [key, child] of collectProperties(root, node)) {
      const at = path === '' ? key : `${path}.${key}`;
      const ann = annotationOf(child);
      if (ann.status === 'removed' || ann.status === 'moved') {
        notes[at] = ann;
        continue;
      }
      const target =
        child.$ref !== undefined && defName(child.$ref) === undefined
          ? resolveRef(root, child.$ref)
          : child;
      walk(target, at, depth + 1);
    }
  };
  walk(root, '', 0);
  return notes;
}

// ---------------------------------------------------------------------------- types

function stripForTypes(root: RootSchema): JSONSchema {
  const clean = (node: unknown): unknown => {
    if (Array.isArray(node)) {
      return node.map(clean);
    }
    if (typeof node !== 'object' || node === null) {
      return node;
    }
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(node)) {
      if (key === 'x-mermaid' || key === 'default' || key === 'required') {
        continue;
      }
      if (key === 'properties') {
        out[key] = Object.fromEntries(
          Object.entries(value as Record<string, SchemaNode>)
            .filter(([, child]) => !isRemoved(child))
            .map(([k, child]) => [k, clean(child)])
        );
      } else if (key === 'allOf') {
        // json-schema-to-typescript makes `interface X extends Base` out of `extends`.
        out.extends = clean(value);
      } else {
        out[key] = clean(value);
      }
    }
    return out;
  };
  return clean(root) as JSONSchema;
}

async function typesSource(root: RootSchema): Promise<string> {
  const ts = await compile(stripForTypes(root), 'MermaidConfig', {
    additionalProperties: false,
    unreachableDefinitions: true,
    bannerComment: BANNER,
    format: false,
  });
  return ts;
}

// ---------------------------------------------------------------------------- docs

const cell = (text = '') =>
  text
    .replace(/\s*\n\s*/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();

interface DocRow {
  path: string;
  type: string;
  def: string;
  status: string;
  notes: string;
  description: string;
}

function typeOf(root: RootSchema, node: SchemaNode): string {
  const target =
    node.$ref !== undefined && defName(node.$ref) === undefined
      ? { ...resolveRef(root, node.$ref), ...node }
      : node;
  if (target.enum !== undefined) {
    return target.enum.map((v) => JSON.stringify(v)).join(' \\| ');
  }
  if (target.tsType !== undefined) {
    return target.tsType.replace(/\|/g, '\\|');
  }
  if (defName(target.$ref) !== undefined) {
    return 'object';
  }
  return target.type === undefined ? 'any' : [target.type].flat().join(' \\| ');
}

function docRows(root: RootSchema): DocRow[] {
  const rows: DocRow[] = [];
  const walk = (node: SchemaNode, path: string, depth: number) => {
    for (const [key, child] of collectProperties(root, node)) {
      const at = path === '' ? key : `${path}.${key}`;
      const ann = annotationOf(child);
      const target =
        child.$ref !== undefined && defName(child.$ref) === undefined
          ? { ...resolveRef(root, child.$ref), ...child }
          : child;
      const fallback =
        defName(child.$ref) !== undefined ? root.$defs[defName(child.$ref)!] : undefined;
      const def = target.default;
      rows.push({
        path: at,
        type: typeOf(root, child),
        def: def === undefined ? '' : `\`${JSON.stringify(def)}\``,
        status: ann.status + (ann.since === undefined ? '' : ` (${ann.since})`),
        notes: [
          ann.movedTo === undefined ? undefined : `Moved to \`${ann.movedTo}\`.`,
          ann.reason,
          ann.replacement === undefined ? undefined : `Replacement: ${ann.replacement}.`,
        ]
          .filter((s) => s !== undefined)
          .join(' '),
        description: target.description ?? fallback?.description ?? '',
      });
      if (ann.status !== 'removed' && depth < 8) {
        walk(target, at, depth + 1);
      }
    }
  };
  walk(root, '', 0);
  return rows;
}

function referenceDoc(root: RootSchema): string {
  const rows = docRows(root);
  const sections = new Set(sectionKeys(root));
  const groups = new Map<string, DocRow[]>();
  for (const row of rows) {
    const head = row.path.split('.')[0]!;
    const group = sections.has(head) ? head : '(top level)';
    groups.set(group, [...(groups.get(group) ?? []), row]);
  }
  const out = [
    '# Mermaid v13 config reference',
    '',
    '<!-- Generated by tools/gen-config from packages/core/schema/config.schema.yaml. Do not edit: run `pnpm gen:config`. -->',
    '',
    'Every config key Mermaid accepts, with its v13 status:',
    '',
    '- **honoured**: v13 implements it.',
    '- **pending**: accepted without a warning; it takes effect once its diagram type or feature is ported (R-CONF-5).',
    '- **ignored**: accepted without a warning, but has no effect in v13.',
    '- **removed**: produces a warning and has no effect.',
    '- **moved**: produces a warning; the key now belongs to another package.',
    '',
    'Keys not listed here produce an "unknown key" warning and are dropped from diagram text. Diagram text (front matter and `%%{init}%%` directives) can never set the keys listed in `secure`, nor the integrator-only options `securityLevel`, limits, `deterministic`, `idPrefix`, `output.cssVariables`, the measurer or link schemes.',
    '',
  ];
  for (const [group, list] of groups) {
    out.push(`## ${group === '(top level)' ? 'Top level' : `\`${group}\``}`, '');
    out.push('| Key | Type | Default | Status | Notes | Description |');
    out.push('| --- | --- | --- | --- | --- | --- |');
    for (const r of list) {
      out.push(
        `| \`${r.path}\` | ${cell(r.type)} | ${cell(r.def)} | ${r.status} | ${cell(r.notes)} | ${cell(r.description)} |`
      );
    }
    out.push('');
  }
  return out.join('\n');
}

function migrationSection(root: RootSchema): string {
  const rows = docRows(root).filter(
    (r) => !r.status.startsWith('pending') && !r.status.startsWith('honoured')
  );
  const changed = docRows(root).filter((r) => /default changes/i.test(r.notes));
  const out = [
    MIGRATION_BEGIN,
    '',
    '## Config',
    '',
    'Generated from the `x-mermaid` annotations in `packages/core/schema/config.schema.yaml`. The full list is in [config-reference.md](./config-reference.md).',
    '',
    '### Removed, moved and ignored keys',
    '',
    '| Key | Status | Reason | Replacement |',
    '| --- | --- | --- | --- |',
  ];
  for (const path of rows.map((r) => r.path)) {
    const node = findKey(root, path);
    const ann = annotationOf(node);
    out.push(
      `| \`${path}\` | ${ann.status}${ann.movedTo === undefined ? '' : ` to \`${ann.movedTo}\``} | ${cell(ann.reason)} | ${cell(ann.replacement)} |`
    );
  }
  out.push('', '### Changed defaults', '', '| Key | v13 default | Reason |', '| --- | --- | --- |');
  for (const r of changed) {
    out.push(
      `| \`${r.path}\` | ${cell(r.def)} | ${cell(annotationOf(findKey(root, r.path)).reason)} |`
    );
  }
  out.push('', MIGRATION_END);
  return out.join('\n');
}

function findKey(root: RootSchema, path: string): SchemaNode {
  let node: SchemaNode = root;
  for (const key of path.split('.')) {
    const target =
      node.$ref !== undefined && defName(node.$ref) === undefined
        ? resolveRef(root, node.$ref)
        : node;
    const next = collectProperties(root, target).get(key);
    if (next === undefined) {
      throw new Error(`no key ${path}`);
    }
    node = next;
  }
  return node;
}

/** Puts the generated section into MIGRATION.md, keeping everything around the markers. */
export function spliceMigration(existing: string | undefined, section: string): string {
  if (existing === undefined) {
    return `# Migrating from Mermaid v12 to v13\n\n${section}\n`;
  }
  const begin = existing.indexOf(MIGRATION_BEGIN);
  const end = existing.indexOf(MIGRATION_END);
  if (begin === -1 || end === -1 || end < begin) {
    return `${existing.trimEnd()}\n\n${section}\n`;
  }
  return existing.slice(0, begin) + section + existing.slice(end + MIGRATION_END.length);
}

// ---------------------------------------------------------------------------- service schema

/**
 * The schema as plain JSON Schema for editors: `required` (it lists keys every resolved
 * config has, not keys front matter must set), `tsType` and `$schema` left out.
 */
function serviceSchema(root: RootSchema): string {
  const DROPPED = new Set(['required', 'tsType', '$schema']);
  // `inProperties`: the keys of this object are config key names, not keywords.
  const clean = (node: unknown, inProperties: boolean): unknown => {
    if (Array.isArray(node)) {
      return node.map((n) => clean(n, false));
    }
    if (typeof node !== 'object' || node === null) {
      return node;
    }
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(node)) {
      if (!inProperties && DROPPED.has(key)) {
        continue;
      }
      out[key] = clean(value, !inProperties && (key === 'properties' || key === '$defs'));
    }
    return out;
  };
  const json = JSON.stringify(clean(root, false), null, 2);
  return (
    `${BANNER}import type { ConfigSchema } from '../config/schema.ts';\n\n` +
    `/** The config JSON schema, for front-matter completion, hover and warnings (D96). */\n` +
    `export const configSchema: ConfigSchema = ${json};\n`
  );
}

// ---------------------------------------------------------------------------- entry

const ts = (value: unknown) => JSON.stringify(value, null, 2);

export interface Generated {
  /** Workspace-relative path to file content. MIGRATION.md is spliced into the existing file. */
  files: Map<string, string>;
}

export class SchemaError extends Error {
  constructor(readonly problems: string[]) {
    super(`config schema has ${problems.length} problem(s):\n${problems.join('\n')}`);
  }
}

/**
 * Generates every derived file from the schema source.
 *
 * @param readExisting - reads a workspace file, `undefined` when it does not exist
 *   (used to splice MIGRATION.md).
 */
export async function generate(
  schemaSource: string,
  readExisting: (path: string) => string | undefined
): Promise<Generated> {
  const root = loadSchema(schemaSource);
  const problems = annotationErrors(root);
  if (problems.length > 0) {
    throw new SchemaError(problems);
  }
  const files = new Map<string, string>();
  files.set(`${CORE_GENERATED}/config.type.ts`, await typesSource(root));
  files.set(
    `${CORE_GENERATED}/defaults.ts`,
    `${BANNER}import type { MermaidConfig } from './config.type.ts';\n\n` +
      `/** Top-level defaults. Diagram sections live in their own packages. */\n` +
      `export const CORE_DEFAULTS: MermaidConfig = ${ts(coreDefaults(root))};\n`
  );
  files.set(`${CORE_GENERATED}/keys.ts`, keyTreeSource(root));
  for (const [section, pkg] of Object.entries(SECTION_OWNERS)) {
    const node = root.properties?.[section];
    if (node === undefined) {
      throw new Error(`section ${section} is not in the schema`);
    }
    const typeName = root.$defs[defName(node.$ref) ?? '']?.title?.replace(/\s+/g, '');
    if (typeName === undefined) {
      throw new Error(`section ${section} must $ref a titled def`);
    }
    const name = `${section}ConfigDefaults`;
    files.set(
      `${pkg}/src/generated/config-defaults.ts`,
      `${BANNER}import type { ${typeName} } from '@mermaid-js/core/config';\n\n` +
        `/** Defaults of the \`${section}\` config section. */\n` +
        `export const ${name}: ${typeName} = ${ts(defaultsOf(root, node) ?? {})};\n`
    );
  }
  files.set(SERVICE_SCHEMA, serviceSchema(root));
  files.set(REFERENCE_DOC, referenceDoc(root));
  files.set(MIGRATION_DOC, spliceMigration(readExisting(MIGRATION_DOC), migrationSection(root)));
  return { files };
}
