import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { generateMirrors, mirrorOf } from './autoload-mirror.ts';
import { FIRST_PARTY_IDS_PATH, generateFirstPartyIds, readManifests } from './registry.ts';

describe('the copies of plugin-autoload inside mermaid (#867)', () => {
  it('are up to date with the package sources', () => {
    const copies = generateMirrors();
    expect(copies.size).toBe(2);
    for (const [path, text] of copies) expect(readFileSync(path, 'utf8'), path).toBe(text);
  });

  it('keep the reference directive first, add the header and name mermaid’s own copy of the scan', () => {
    const copy = mirrorOf(
      [
        '/// <reference types="node" />',
        "import type { ExtensionPlugin } from '@mermaid-js/core';",
        "import { scanPlugins } from './scan.ts';",
        '',
      ].join('\n'),
      'packages/x/src/load.ts'
    );
    expect(copy.split('\n')).toEqual([
      '/// <reference types="node" />',
      '// Generated by `pnpm gen:registry` (tools/gen-config/src/autoload-mirror.ts) from packages/x/src/load.ts. Do not edit.',
      "import type { ExtensionPlugin } from '@mermaid-js/core';",
      "import { scanPlugins } from './autoload-scan.gen.ts';",
      '',
    ]);
    expect(mirrorOf('export {};\n', 'a.ts').startsWith('// Generated by')).toBe(true);
  });
});

describe('plugin-autoload’s first-party ids', () => {
  it('are up to date and list each id once', () => {
    const text = generateFirstPartyIds(readManifests());
    expect(readFileSync(FIRST_PARTY_IDS_PATH, 'utf8')).toBe(text);
    const ids = [...text.matchAll(/^ {2}'([^']+)',$/gm)].map((m) => m[1]);
    expect(ids).toEqual(expect.arrayContaining(['flowchart', 'sequence', 'pie', 'gitGraph']));
    expect(new Set(ids).size).toBe(ids.length);
  });
});
