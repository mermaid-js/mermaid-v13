/**
 * The type × format support matrix (D58, R-ASCII-5): `v13/docs/format-matrix.md`, written by
 * `pnpm gen:registry` from the same `mermaid` manifests as the registry. `format-matrix.spec.ts`
 * fails when the committed file is stale, so `pnpm test` (and `pnpm check`) catch it.
 */
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { ManifestSource } from './registry.ts';
import { formatsOf, V12_DETECTORS } from './registry.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
export const FORMAT_MATRIX_PATH = join(ROOT, 'v13/docs/format-matrix.md');

/** Output formats, in column order (`RenderOptions.format`). */
const FORMATS = ['svg', 'ascii'] as const;
const HEADINGS: Record<(typeof FORMATS)[number], string> = { svg: 'SVG', ascii: 'ASCII' };

export function generateFormatMatrix(manifests: readonly ManifestSource[]): string {
  const byType = new Map<string, ManifestSource>();
  for (const m of manifests) {
    for (const f of m.manifest.formats) {
      if (!(FORMATS as readonly string[]).includes(f))
        throw new Error(`${m.name}: unknown format "${f}" (${FORMATS.join(', ')})`);
    }
    for (const type of m.manifest.types) byType.set(type, m);
  }
  const lines = [
    '# Diagram types and output formats',
    '',
    '<!-- Generated by `pnpm gen:registry` (tools/gen-config/src/format-matrix.ts) from the `mermaid` manifests in packages/diagram-*/package.json. Do not edit. -->',
    '',
    'Which output formats each diagram type supports in v13 (D58, R-ASCII-5). Rows follow v12',
    'detection order. Check at run time with `supportsFormat(type, format)`; asking for a format a type',
    'does not support throws `UnsupportedFormatError`. See [ASCII output](ascii.md) for text output.',
    '',
    `| Diagram type | Package | ${FORMATS.map((f) => HEADINGS[f]).join(' | ')} |`,
    `| --- | --- | ${FORMATS.map(() => '---').join(' | ')} |`,
  ];
  for (const [type] of V12_DETECTORS) {
    const m = byType.get(type);
    const cells = FORMATS.map((f) => (m && formatsOf(m, type).includes(f) ? 'yes' : 'no'));
    lines.push(`| \`${type}\` | ${m ? `\`${m.name}\`` : 'not ported'} | ${cells.join(' | ')} |`);
  }
  lines.push('');
  return lines.join('\n');
}
