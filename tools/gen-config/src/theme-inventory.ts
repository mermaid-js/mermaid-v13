/**
 * The theme variable inventory (DESIGN §8.3, O-1): name, CSS variable, base/derived/token,
 * the shared light and dark rules, the built-in themes that set a literal value, and the
 * diagram types that read it; then each diagram package's own variables (spec #414 T0b), with
 * their value in every theme. Written to `v13/docs/theme-variables.md`.
 */
import { fileURLToPath } from 'node:url';
import {
  BASE_VARIABLES,
  DARK_RULES,
  LIGHT_RULES,
  NUMBERED_PALETTES,
  PALETTE_LIMITS,
  PALETTE_VARIABLES,
  THEME_NAMES,
  THEME_VARIABLES,
  TOKEN_VARIABLES,
  createTheme,
  loadTheme,
  type ThemeSpec,
  type NumberedPalette,
} from '../../../packages/core/src/theme/index.ts';
import { runtimeVars, type ThemePackage } from './theme-packages.ts';

export const INVENTORY_PATH = fileURLToPath(
  new URL('../../../v13/docs/theme-variables.md', import.meta.url)
);

export const TABLE_PATH = fileURLToPath(
  new URL('../../../packages/core/src/theme/generated/variables.ts', import.meta.url)
);

/**
 * The runtime half of the vocabulary: each variable's alias and kind, in vocabulary order.
 * `usedBy` is documentation, so it stays in `vocabulary.ts`, which only tools and specs read
 * as data; the runtime closure carries this table instead.
 */
export function themeTable(): string {
  const rows = Object.entries(THEME_VARIABLES).map(([name, d]) => `${name} ${d.alias} ${d.kind}`);
  // One string of name, alias and kind triples, split at load: smaller gzipped than objects.
  return [
    '// Generated by tools/gen-config from packages/core/src/theme/vocabulary.ts.',
    '// Do not edit: run `pnpm gen:theme`.',
    '',
    "import type { ThemeVarEntry, ThemeVarKind } from '../vocabulary.ts';",
    '',
    `const ROWS = '${rows.join(' ')}'.split(' ');`,
    '',
    "/** Each theme variable's alias and kind: `THEME_VARIABLES` without `usedBy`. */",
    'export const THEME_VARIABLE_TABLE: Readonly<Record<string, ThemeVarEntry>> = {};',
    'for (let i = 0; i < ROWS.length; i += 3)',
    '  (THEME_VARIABLE_TABLE as Record<string, ThemeVarEntry>)[ROWS[i]!] = {',
    '    alias: ROWS[i + 1]!,',
    '    kind: ROWS[i + 2] as ThemeVarKind,',
    '  };',
    '',
  ].join('\n');
}

const code = (s: string | undefined): string => (s === undefined ? '' : '`' + s + '`');

/**
 * A package's variables, each resolved through `createTheme(spec, { diagram })` in every theme
 * (the theme's family and dark traits pick the table's entries), with the nested form (D540).
 */
function packageSection(pkg: ThemePackage, specs: readonly ThemeSpec[]): string[] {
  const vars = runtimeVars(pkg.vocabulary ?? {});
  const diagram = pkg.table ?? { vars, rules: { light: {} } };
  const themes = specs.map((spec) => createTheme(spec, { diagram, cssVariables: false }));
  const rows = Object.entries(vars).map(([name, d]) => {
    const nested =
      d.nested === undefined || diagram.section === undefined
        ? ''
        : code(`${diagram.section}.${d.nested}`);
    const cells = [code(name), nested, d.kind, ...themes.map((t) => code(t.value(name)))];
    return '| ' + cells.join(' | ').replace(/ {2}/g, ' ') + ' |';
  });
  return [
    '',
    `### ${pkg.type}`,
    '',
    `| Variable | Nested | Kind | ${specs.map((s) => s.name).join(' | ')} |`,
    `| --- | --- | --- | ${specs.map(() => '---').join(' | ')} |`,
    ...rows,
  ];
}

export async function themeInventory(packages: readonly ThemePackage[] = []): Promise<string> {
  const specs = await Promise.all(THEME_NAMES.map((n) => loadTheme(n)));
  const base = new Set<string>(BASE_VARIABLES);
  const tokens = new Set<string>(TOKEN_VARIABLES);
  const rows = Object.entries(THEME_VARIABLES).map(([name, def]) => {
    const role = base.has(name) ? 'base' : tokens.has(name) ? 'token' : 'derived';
    const setBy =
      role === 'derived'
        ? specs
            .filter((s) => s.values?.[name] !== undefined || s.rules?.[name] !== undefined)
            .map((s) => s.name)
            .join(', ')
        : 'all';
    const cells = [
      code(name),
      code(`--mermaid-${name}`),
      role,
      def.kind,
      code(LIGHT_RULES[name]),
      code(DARK_RULES[name]),
      setBy,
      def.usedBy.join(', '),
    ];
    return '| ' + cells.join(' | ').replace(/ {2}/g, ' ') + ' |';
  });
  const palettes = PALETTE_VARIABLES.map((name) => {
    const names = NUMBERED_PALETTES.includes(name as NumberedPalette)
      ? `${code(name)}, ${code(name + '0')}–${code(name + String(PALETTE_LIMITS[name as NumberedPalette] - 1))}`
      : code(name);
    const carriers = specs.filter((s) => (s.palettes?.[name]?.length ?? 0) > 0);
    const setBy = carriers.length === specs.length ? 'all' : carriers.map((s) => s.name).join(', ');
    return `| ${code(name)} | ${names} | ${setBy} |`;
  });
  return [
    '# Theme variables',
    '',
    '<!-- Generated by `pnpm gen:theme` from packages/core/src/theme. Do not edit. -->',
    '',
    'Every variable is exposed as a CSS custom property `--mermaid-<name>` and can be set in',
    '`themeVariables`. A **base** variable is set by every theme (at most 8, R-THEME-5); a',
    '**derived** one follows its rule unless a theme or the author sets it; a **token** is a',
    'shape token (R-THEME-11). Rules are in the derivation DSL (`mix`, `lighten`, `darken`,',
    '`lightenHsl`, `darkenHsl`, `alpha`, `contrast`, `invert`, `adjustHue`, `ifSet`) and compile',
    'to CSS (`color-mix(in srgb, …)`, relative colours). Variables of',
    'diagram types that are not ported yet are accepted and ignored (R-CONF-5).',
    '',
    '| Variable | CSS variable | Role | Kind | Light rule | Dark rule | Set by themes | Used by |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
    '## Palettes',
    '',
    'Lists of colours a theme carries as data (D151, D152), read as literal colours rather than',
    'CSS variables. In `themeVariables` a whole list is an array of colours or a comma-separated',
    'string; `cScale0`–`cScale11`, `cScaleInv0`–`cScaleInv11` and `cScaleLabel0`–`cScaleLabel11`',
    'replace one entry. A theme entry can be a rule over the base colours and other palette',
    'entries, so `cScaleInv` and `cScaleLabel` follow an override of `cScale` or `primaryColor` as',
    'in v12 (D258). A theme not listed carries an empty list.',
    '',
    '| Palette | `themeVariables` names | Set by themes |',
    '| --- | --- | --- |',
    ...palettes,
    ...diagramSections(packages, specs),
    '',
  ].join('\n');
}

function diagramSections(packages: readonly ThemePackage[], specs: readonly ThemeSpec[]): string[] {
  const owners = packages.filter((p) => p.vocabulary !== undefined);
  if (owners.length === 0) return [];
  return [
    '',
    '## Diagram variables',
    '',
    "Each diagram package's own variables (D331), listed in its `src/theme/vocabulary.ts` and",
    'loaded with the diagram, never with core. The values are what `createTheme(spec, { diagram })`',
    "resolves in each theme: a table is keyed by the theme's family and dark traits, never by its",
    'name. **Nested** is the same variable under `themeVariables.<section>` (D540); the flat name',
    'wins when an author sets both. Each is also a CSS variable `--mermaid-<name>`, apart from',
    'flags and opacities, which are read literally.',
    ...owners.flatMap((p) => packageSection(p, specs)),
  ];
}
