/**
 * The copies of `@mermaid-js/plugin-autoload`'s scan and loader inside `mermaid` (spec #867,
 * D589). The package is the home of that code and `mermaid` must not depend on it (its bin
 * has no dependency, R-PERF-2), yet until ticket 4 removes `mermaid`'s first-use Node
 * discovery and `mermaid/node-scan` they still need it. Writing the copy here, instead of
 * keeping a second hand-written one, leaves one source: `pnpm gen:registry --check` fails when
 * a copy is stale. The import of the scan becomes its copy. Delete this file with
 * its two outputs in ticket 4.
 */
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');

export interface Mirror {
  /** The source, relative to the workspace root. */
  readonly from: string;
  /** The copy, relative to the workspace root. */
  readonly to: string;
}

export const MIRRORS: readonly Mirror[] = [
  {
    from: 'packages/plugin-autoload/src/scan.ts',
    to: 'packages/mermaid/src/generated/autoload-scan.gen.ts',
  },
  {
    from: 'packages/plugin-autoload/src/load.ts',
    to: 'packages/mermaid/src/generated/autoload-load.gen.ts',
  },
];

/** `[from, to]` rewrites of the import specifiers that differ inside `mermaid`. */
const REWRITES: readonly (readonly [string, string])[] = [
  ["from './scan.ts';", "from './autoload-scan.gen.ts';"],
];

/** The copy of `source` (the text of a mirrored file): a header, then the rewritten text. */
export function mirrorOf(source: string, from: string): string {
  let text = source;
  for (const [a, b] of REWRITES) text = text.split(a).join(b);
  const header = `// Generated by \`pnpm gen:registry\` (tools/gen-config/src/autoload-mirror.ts) from ${from}. Do not edit.\n`;
  // The reference directive must stay first.
  const directive = '/// <reference types="node" />\n';
  return text.startsWith(directive)
    ? `${directive}${header}${text.slice(directive.length)}`
    : `${header}${text}`;
}

/** Absolute path → content of every copy. */
export function generateMirrors(root = ROOT): Map<string, string> {
  return new Map(
    MIRRORS.map(({ from, to }) => [
      join(root, to),
      mirrorOf(readFileSync(join(root, from), 'utf8'), from),
    ])
  );
}
